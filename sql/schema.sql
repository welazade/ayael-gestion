    'by_product', (select coalesce(jsonb_agg(r order by r.total desc), '[]') from (
        select pr.name, pr.direction, count(*) n, sum(o.amount) total
        from operations o join products pr on pr.id = o.product_id
        where o.kind = 'caisse' and o.status = 'ok' and o.op_day between d1 and d2 and (ag is null or o.agence_id = ag)
        group by pr.name, pr.direction) r),
    'by_gtp', (select coalesce(jsonb_agg(r order by r.amount desc), '[]') from (
        select a.name, a.bank, count(*) filter (where o.kind = 'recharge') n,
               coalesce(sum(o.amount) filter (where o.kind = 'recharge'), 0) amount,
               coalesce(sum(o.commission) filter (where o.kind = 'recharge'), 0) commission,
               coalesce(sum(o.amount) filter (where o.kind = 'approvisionnement'), 0) appro
        from operations o join accounts a on a.id = o.account_id
        where a.kind = 'gtp' and o.status = 'ok' and o.op_day between d1 and d2
          and o.kind in ('recharge','approvisionnement') and (ag is null or o.agence_id = ag)
        group by a.name, a.bank) r),
    'by_agent', (select coalesce(jsonb_agg(r order by r.agent), '[]') from (
        select coalesce(pf.full_name, '?') agent, count(*) n,
               count(*) filter (where o.kind = 'recharge') recharges_n,
               coalesce(sum(o.amount) filter (where o.kind = 'recharge'), 0) recharges_amount,
               coalesce(sum(o.commission) filter (where o.kind = 'recharge'), 0) commission,
               count(*) filter (where o.kind = 'caisse') caisse_n,
               coalesce(sum(o.amount) filter (where o.kind = 'depense'), 0) depenses,
               (select count(*) from operations x where x.user_id = o.user_id and x.status = 'annulee' and x.op_day between d1 and d2
                  and (ag is null or x.agence_id = ag)) annulees
        from operations o left join profiles pf on pf.id = o.user_id
        where o.status = 'ok' and o.op_day between d1 and d2 and o.kind in ('caisse','recharge','depense') and (ag is null or o.agence_id = ag)
        group by pf.full_name, o.user_id) r),
    'by_month', (select coalesce(jsonb_agg(r order by r.month, r.name), '[]') from (
        select to_char(date_trunc('month', o.op_day), 'YYYY-MM') as month, a.name,
               count(*) n, sum(o.amount) amount, sum(o.commission) commission,
               count(*) filter (where o.commission_status = 'estimee') to_check
        from operations o join accounts a on a.id = o.account_id
        where o.kind = 'recharge' and o.status = 'ok' and o.op_day between d1 and d2 and (ag is null or o.agence_id = ag)
        group by 1, a.name) r),
    'depenses', (select coalesce(jsonb_agg(r order by r.total desc), '[]') from (
        select coalesce(category, 'Autre') category, count(*) n, sum(amount) total
        from operations where kind = 'depense' and status = 'ok' and op_day between d1 and d2 and (ag is null or agence_id = ag)
        group by 1) r),
    'closings', (select coalesce(jsonb_agg(r order by r.agent), '[]') from (
        select pf.full_name agent, count(*) n, sum(c.gap) gap, sum(c.handed) handed
        from closings c join profiles pf on pf.id = c.agent_id
        where c.status = 'validee' and c.day between d1 and d2 and (ag is null or c.agence_id = ag) group by pf.full_name) r)
  );
end $$;

