  if a.kind = 'gtp' and me.role <> 'gerante' then raise exception 'Compte non autorisé.'; end if;
  perform _check_funds(a, amt);
  insert into operations(user_id, kind, account_id, amount, details, category)
  values (me.id, 'depense', a.id, amt, motif, _txt(p,'category')) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt);
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(a.id));
end $$;

