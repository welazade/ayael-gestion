-- ---------- Agences : création et soldes avec l'agence principale ----------

create or replace function save_agence(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; gid bigint := _num(p,'id')::bigint; r agences;
begin
  me := _require('gerante');
  if _txt(p,'name') is null then raise exception 'Le nom de l''agence est obligatoire.'; end if;
  if exists (select 1 from agences where upper(name) = upper(_txt(p,'name')) and id is distinct from gid) then
    raise exception 'Une agence porte déjà ce nom.';
  end if;
  if gid is null then
    insert into agences(name) values (_txt(p,'name')) returning * into r;
  else
    update agences set name = _txt(p,'name'),
      active = case when is_main then true else coalesce((p->>'active')::boolean, active) end
    where id = gid returning * into r;
    if r.id is null then raise exception 'Agence introuvable.'; end if;
  end if;
  perform _coffre_of(r.id);
  update accounts set name = case when r.is_main then 'Coffre' else 'Coffre ' || r.name end
    where kind = 'coffre' and agence_id = r.id and (name = 'Coffre' or name like 'Coffre %');
  perform _log('agences');
  return to_jsonb(r);
end $$;

-- Détail du solde entre une agence et l'agence principale : chaque opération qui le fait bouger.
create or replace function liaison_detail(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; ag bigint := _num(p,'agence_id')::bigint;
        d1 date := coalesce(_txt(p,'from')::date, '2000-01-01'); d2 date := coalesce(_txt(p,'to')::date, current_date);
begin
  me := _require('manager');
  if me.role in ('gerant','sous_gerant') then ag := me.agence_id; end if;
  if ag is null or ag = _main() then raise exception 'Choisissez une agence secondaire.'; end if;
  return jsonb_build_object(
    'agence', (select name from agences where id = ag),
    'balance', _liaison(ag),
    'lines', (
      select coalesce(jsonb_agg(_op_row(o) || jsonb_build_object('liaison', x.amt) order by o.created_at desc, o.id desc), '[]')
      from (select m.operation_id, sum(m.amount) amt
            from movements m join accounts a on a.id = m.account_id
            where coalesce(a.agence_id, _main()) = ag
              and exists (select 1 from movements m2 join accounts a2 on a2.id = m2.account_id
                          where m2.operation_id = m.operation_id and coalesce(a2.agence_id, _main()) <> ag)
            group by m.operation_id having sum(m.amount) <> 0) x
      join operations o on o.id = x.operation_id
      where o.op_day between d1 and d2));
end $$;

-- ---------- Clôture du soir --------------------------------------------

create or replace function closing_preview(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; uid uuid; acc bigint; last closings; since timestamptz;
begin
  me := _require(null);
  uid := case when me.role <> 'agent' and _txt(p,'agent_id') is not null then _txt(p,'agent_id')::uuid else me.id end;
  if me.role in ('gerant','sous_gerant') and (select agence_id from profiles where id = uid) is distinct from me.agence_id then
    raise exception 'Cet agent appartient à une autre agence.';
  end if;
  acc := _caisse_of(uid);
  select * into last from closings where agent_id = uid and status <> 'rejetee' order by created_at desc, id desc limit 1;
  since := coalesce(last.created_at, '-infinity'::timestamptz);
  return jsonb_build_object(
    'account_id', acc,
    'expected', _bal(acc),
    'last', to_jsonb(last),
    'pending', exists (select 1 from closings where agent_id = uid and status = 'soumise'),
    'summary', (
      select coalesce(jsonb_agg(jsonb_build_object('label', label, 'n', n, 'in', vin, 'out', vout) order by label), '[]') from (
        select coalesce(pr.name, case o.kind when 'recharge' then 'Recharges ' || a.name when 'depense' then 'Dépenses'
                                    when 'avoir' then case o.category when 'credit' then 'Ventes à crédit (non encaissées)' when 'reglement' then 'Règlements de clients' else 'Monnaie des clients' end
                                    else initcap(o.kind) end) as label,
               count(distinct o.id) as n,
               coalesce(sum(m.amount) filter (where m.amount > 0), 0) as vin,
               coalesce(-sum(m.amount) filter (where m.amount < 0), 0) as vout
        from operations o
        join movements m on m.operation_id = o.id and m.account_id = acc and not m.reversal
        left join products pr on pr.id = o.product_id
        left join accounts a on a.id = o.account_id
        where o.status = 'ok' and o.created_at > since
        group by 1) s)
  );
end $$;

create or replace function closing_submit(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; acc bigint; exp numeric; cnt numeric := _num(p,'counted'); hd numeric := coalesce(_num(p,'handed'), 0); cid bigint;
begin
  me := _require(null);
  if cnt is null or cnt < 0 then raise exception 'Indiquez le montant compté.'; end if;
  if hd < 0 or hd > cnt then raise exception 'Le montant remis doit être entre 0 et le montant compté.'; end if;
  if exists (select 1 from closings where agent_id = me.id and status = 'soumise') then
    raise exception 'Une clôture attend déjà la validation de la gérante.';
  end if;
  acc := _caisse_of(me.id);
  exp := _bal(acc);
  insert into closings(agent_id, account_id, expected, counted, gap, handed, note)
  values (me.id, acc, exp, cnt, cnt - exp, hd, _txt(p,'note')) returning id into cid;
  update operations set closing_id = cid where user_id = me.id and closing_id is null;
  perform _log('closings');
  return jsonb_build_object('ok', true, 'id', cid, 'expected', exp, 'gap', cnt - exp);
end $$;

create or replace function closing_validate(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; c closings; oid bigint; cof bigint; nm text;
begin
  me := _require_perm('clotures');
  select * into c from closings where id = _num(p,'id')::bigint for update;
  if c.id is null then raise exception 'Clôture introuvable.'; end if;
  if c.status <> 'soumise' then raise exception 'Cette clôture a déjà été traitée.'; end if;
  if me.role in ('gerant','sous_gerant') and c.agence_id is distinct from me.agence_id then
    raise exception 'Cette clôture appartient à une autre agence.';
  end if;
  select full_name into nm from profiles where id = c.agent_id;
  if not _bool(p, 'accept') then
    update closings set status = 'rejetee', validated_by = me.id, validated_at = now(), manager_note = _txt(p,'note') where id = c.id;
    update operations set closing_id = null where closing_id = c.id;
  else
    if c.gap <> 0 then
      insert into operations(user_id, kind, account_id, amount, details, closing_id)
      values (me.id, 'ajustement', c.account_id, c.gap,
              'Écart de clôture du ' || to_char(c.day, 'DD/MM/YYYY') || ' (' || nm || ')', c.id) returning id into oid;
      insert into movements(operation_id, account_id, amount) values (oid, c.account_id, c.gap);
    end if;
    if c.handed > 0 then
      cof := _coffre_of(c.agence_id);
      insert into operations(user_id, kind, account_id, account2_id, amount, details, closing_id)
      values (me.id, 'cloture', c.account_id, cof, c.handed,
              'Remise de caisse du ' || to_char(c.day, 'DD/MM/YYYY') || ' (' || nm || ')', c.id) returning id into oid;
      insert into movements(operation_id, account_id, amount) values (oid, c.account_id, -c.handed), (oid, cof, c.handed);
    end if;
    update closings set status = 'validee', validated_by = me.id, validated_at = now(), manager_note = _txt(p,'note') where id = c.id;
  end if;
  perform _log('closings');
  return jsonb_build_object('ok', true);
end $$;

create or replace function list_closings(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; st text := _txt(p,'status'); lim int := coalesce(_num(p,'limit')::int, 60); ag bigint;
begin
  me := _require(null);
  ag := _scope(me, p);
  return (
    select coalesce(jsonb_agg(r order by r.created_at desc), '[]') from (
      select c.*, a.full_name as agent, v.full_name as validated_by_name, acc.name as account,
             (select name from agences where id = c.agence_id) as agence
      from closings c
      left join profiles a on a.id = c.agent_id
      left join profiles v on v.id = c.validated_by
      left join accounts acc on acc.id = c.account_id
      where (me.role <> 'agent' or c.agent_id = me.id) and (ag is null or c.agence_id = ag) and (st is null or c.status = st)
      order by c.created_at desc limit lim) r);
end $$;

-- ---------- Rapports ------------------------------------------------------

create or replace function report(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; d1 date := coalesce(_txt(p,'from')::date, date_trunc('month', current_date)::date);
        d2 date := coalesce(_txt(p,'to')::date, current_date); ag bigint;
begin
  me := _require_perm('clotures');
  ag := _scope(me, p);
  return jsonb_build_object(
    'from', d1, 'to', d2, 'agence_id', ag,
    'by_agence', (select coalesce(jsonb_agg(r order by r.is_main desc, r.agence), '[]') from (
        select g.name agence, g.is_main,
               count(o.id) filter (where o.kind in ('caisse','recharge','depense')) n,
