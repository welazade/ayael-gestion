-- Mise en place des agences sur des données existantes (une seule fois).
do $$
declare m bigint;
begin
  if not exists (select 1 from settings where key = 'migration_agences') then
    select id into m from agences where is_main order by id limit 1;
    update profiles set agence_id = m where agence_id is null;
    -- Caisses, coffre et comptes électroniques propres : à l'agence principale.
    -- GTP, banque, Wave, Orange Money, RIA, Western Union : communs (agence vide).
    update accounts a set agence_id = coalesce((select agence_id from profiles where id = a.agent_id), m)
      where agence_id is null and (kind in ('caisse','coffre')
        or (kind = 'electronique' and name not in ('Wave','Orange Money','RIA','Western Union')));
    update operations o set agence_id = coalesce((select agence_id from profiles where id = o.user_id), m) where agence_id is null;
    update closings c set agence_id = coalesce((select agence_id from profiles where id = c.agent_id), m) where agence_id is null;
    insert into settings(key, value) values ('migration_agences', 'true');
  end if;
end $$;

-- ---------- Fonctions internes -----------------------------------------

create or replace function _num(p jsonb, k text) returns numeric
language sql immutable as $$
  select nullif(replace(replace(trim(coalesce(p->>k,'')),' ',''),',','.'),'')::numeric
$$;

create or replace function _txt(p jsonb, k text) returns text
language sql immutable as $$ select nullif(trim(coalesce(p->>k,'')),'') $$;

create or replace function _bool(p jsonb, k text) returns boolean
language sql immutable as $$ select coalesce((p->>k)::boolean, false) $$;

create or replace function _log(w text) returns void
language plpgsql security definer set search_path = public as $$
begin
  delete from change_log where at < now() - interval '1 day';
  insert into change_log(what) values (w);
end $$;

create or replace function _require(need text default null) returns profiles
language plpgsql security definer set search_path = public as $$
declare r profiles;
begin
  select * into r from profiles where id = auth.uid();
  if r.id is null then raise exception 'Vous n''êtes pas connecté(e).'; end if;
  if not r.active then raise exception 'Compte non activé. Demandez à la gérante de l''activer.'; end if;
  if need = 'gerante' and r.role <> 'gerante' then raise exception 'Action réservée à la direction (gérante de l''agence principale).'; end if;
  if need = 'manager' and r.role = 'agent' then raise exception 'Action réservée aux gérants.'; end if;
  if need = 'caisse' and r.role = 'agent' and not r.can_caisse then raise exception 'Vous n''avez pas le droit de saisir des opérations de caisse.'; end if;
  if need = 'recharge' and r.role = 'agent' and not r.can_recharge then raise exception 'Vous n''avez pas le droit de saisir des recharges.'; end if;
  return r;
end $$;

-- Droit d'une personne : la direction et les gérants d'agence ont tout ; un sous-gérant ce qui est coché.
create or replace function _can(me profiles, perm text) returns boolean
language sql stable as $$
  select case
    when me.role in ('gerante','gerant') then true
    when me.role = 'sous_gerant' then case perm
      when 'appro' then me.perm_appro when 'produits' then me.perm_produits when 'ajust' then me.perm_ajust
      when 'clotures' then me.perm_clotures when 'fournisseurs' then me.perm_fournisseurs else false end
    else false end
$$;

create or replace function _require_perm(perm text) returns profiles
language plpgsql security definer set search_path = public as $$
declare r profiles;
begin
  r := _require(null);
  if not _can(r, perm) then
    raise exception 'Vous n''avez pas ce droit (%). Demandez à la direction.', case perm
      when 'appro' then 'approvisionner' when 'produits' then 'produits' when 'ajust' then 'ajuster les soldes'
      when 'clotures' then 'clôtures et rapports' when 'fournisseurs' then 'fournisseurs' else perm end;
  end if;
  return r;
end $$;

-- L'agence principale.
create or replace function _main() returns bigint
language sql stable security definer set search_path = public as $$
  select id from agences where is_main order by id limit 1
$$;

-- Agence à afficher : la direction choisit (vide = toutes) ; un gérant ou un agent voit la sienne.
create or replace function _scope(me profiles, p jsonb) returns bigint
language sql stable as $$
  select case when me.role = 'gerante' then _num(p, 'agence_id')::bigint else me.agence_id end
$$;

-- Un compte est visible dans une agence s'il lui appartient ou s'il est commun.
create or replace function _acc_in(a accounts, ag bigint) returns boolean
language sql stable as $$
  select ag is null or a.agence_id is null or a.agence_id = ag
$$;

-- Solde entre une agence et l'agence principale (positif = l'agence doit à la principale).
-- = l'argent entré (ou sorti) sur les comptes de l'agence lors d'opérations qui touchent
--   aussi des comptes d'une autre agence ou des comptes communs.
create or replace function _liaison(ag bigint) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(m.amount), 0)
  from movements m join accounts a on a.id = m.account_id
  where coalesce(a.agence_id, _main()) = ag
    and exists (select 1 from movements m2 join accounts a2 on a2.id = m2.account_id
                where m2.operation_id = m.operation_id and coalesce(a2.agence_id, _main()) <> ag)
$$;

create or replace function _bal(acc bigint) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(amount), 0) from movements where account_id = acc
$$;

create or replace function _caisse_of(uid uuid) returns bigint
language plpgsql security definer set search_path = public as $$
declare a bigint; n text;
begin
  select id into a from accounts where kind = 'caisse' and agent_id = uid order by id limit 1;
  if a is null then
    select full_name into n from profiles where id = uid;
    insert into accounts(name, kind, agent_id, sort, agence_id)
      values ('Caisse ' || coalesce(nullif(n, ''), 'agent'), 'caisse', uid, 50,
              coalesce((select agence_id from profiles where id = uid), _main()))
      returning id into a;
  end if;
  return a;
end $$;

-- Coffre d'une agence (créé au besoin).
create or replace function _coffre_of(ag bigint) returns bigint
language plpgsql security definer set search_path = public as $$
declare a bigint; nm text;
begin
  ag := coalesce(ag, _main());
  select id into a from accounts where kind = 'coffre' and active and agence_id = ag order by sort, id limit 1;
  if a is null then
    select name into nm from agences where id = ag;
    insert into accounts(name, kind, sort, agence_id)
      values (case when ag = _main() then 'Coffre' else 'Coffre ' || nm end, 'coffre', 60, ag) returning id into a;
  end if;
  return a;
end $$;

create or replace function _coffre() returns bigint
language sql security definer set search_path = public as $$ select _coffre_of(_main()) $$;

-- Rattache automatiquement chaque opération et chaque clôture à l'agence de la personne.
create or replace function _set_agence() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.agence_id is null then
    if tg_table_name = 'closings' then
      new.agence_id := coalesce((select agence_id from profiles where id = new.agent_id), _main());
    else
      new.agence_id := coalesce((select agence_id from profiles where id = new.user_id), _main());
    end if;
  end if;
  return new;
end $$;
drop trigger if exists operations_agence on operations;
create trigger operations_agence before insert on operations for each row execute function _set_agence();
drop trigger if exists closings_agence on closings;
create trigger closings_agence before insert on closings for each row execute function _set_agence();

create or replace function _commission(acc bigint, amt numeric) returns numeric
language plpgsql stable security definer set search_path = public as $$
declare a accounts; v numeric;
begin
  select * into a from accounts where id = acc;
  if a.id is null or coalesce(a.comm_rate, 0) = 0 or amt is null then return 0; end if;
  v := amt * a.comm_rate / 100 / nullif(a.comm_divisor, 0);
  v := case a.comm_rounding when 'ceil' then ceil(v) when 'floor' then floor(v) else round(v) end;
  return greatest(v, coalesce(a.comm_min, 0));
end $$;

-- Un agent ne peut utiliser que sa propre caisse ou les comptes électroniques / banque.
create or replace function _check_use(me profiles, acc bigint) returns accounts
language plpgsql security definer set search_path = public as $$
declare a accounts;
begin
  select * into a from accounts where id = acc;
  if a.id is null then raise exception 'Compte introuvable.'; end if;
  if not a.active then raise exception 'Le compte « % » est désactivé.', a.name; end if;
  if me.role <> 'gerante' then
    if a.agence_id is not null and a.agence_id is distinct from me.agence_id then
      raise exception 'Le compte « % » appartient à une autre agence.', a.name;
    end if;
    if a.kind = 'caisse' and a.agent_id is distinct from me.id then
      raise exception 'Vous ne pouvez utiliser que votre propre caisse.';
    end if;
    if a.kind = 'gtp' or (a.kind = 'coffre' and me.role = 'agent') then
      raise exception 'Le compte « % » ne peut pas être utilisé ici.', a.name;
    end if;
  end if;
  return a;
end $$;

-- Vérifie qu'un compte peut supporter une sortie de « amt ».
create or replace function _check_funds(a accounts, amt numeric) returns void
language plpgsql security definer set search_path = public as $$
declare b numeric;
begin
  if a.allow_negative then return; end if;
  b := _bal(a.id);
  if b - amt < 0 then
    raise exception 'Solde insuffisant sur « % » : % F disponibles, % F demandés.',
      a.name, replace(to_char(b, 'FM999,999,999,990'), ',', ' '), replace(to_char(amt, 'FM999,999,999,990'), ',', ' ');
  end if;
end $$;

create or replace function _op_row(o operations) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(o) || jsonb_build_object(
    'product',      (select name from products where id = o.product_id),
    'direction',    (select direction from products where id = o.product_id),
    'card_number',  (select card_number from cards where id = o.card_id),
    'holder_name',  (select holder_name from cards where id = o.card_id),
    'account',      (select name from accounts where id = o.account_id),
    'account_kind', (select kind from accounts where id = o.account_id),
    'account2',     (select name from accounts where id = o.account2_id),
    'agent',        (select full_name from profiles where id = o.user_id),
    'cancelled_by_name', (select full_name from profiles where id = o.cancelled_by),
    'fournisseur',  (select name from accounts where id = o.fournisseur_id),
    'client_name',  coalesce((select name from clients where id = o.client_id),
                             (select client_name from receipts where id = o.receipt_id))
  )
$$;

-- Nom simplifié pour comparer : majuscules, sans ponctuation ni espaces en trop.
create or replace function _norm_name(nm text) returns text
language sql immutable as $$
  select trim(regexp_replace(regexp_replace(upper(coalesce(nm, '')), '[^A-Z0-9À-ÖØ-Ý]+', ' ', 'g'), '\s+', ' ', 'g'))
$$;
create index if not exists clients_norm_idx on clients (_norm_name(name));

-- Retrouve un client par son nom (même écrit un peu différemment), ou le crée.
create or replace function _client_for(nm text, ph text default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare cid bigint; n text := upper(trim(regexp_replace(coalesce(nm, ''), '\s+', ' ', 'g')));
begin
  if n = '' then return null; end if;
  select id into cid from clients where _norm_name(name) = _norm_name(n) order by id limit 1;
  if cid is null then
    insert into clients(name, phone) values (n, nullif(trim(coalesce(ph, '')), '')) returning id into cid;
  end if;
  return cid;
end $$;

-- ---------- Création automatique du profil à l'inscription -------------
-- La toute première personne inscrite devient la gérante (compte actif).
-- Les suivantes sont des agents en attente d'activation.

create or replace function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare first_user boolean;
begin
  select not exists (select 1 from profiles where role = 'gerante') into first_user;
  insert into profiles(id, full_name, login, role, active, agence_id)
  values (new.id,
          coalesce(nullif(new.raw_user_meta_data->>'full_name', ''), split_part(new.email, '@', 1)),
          split_part(new.email, '@', 1),
          case when first_user then 'gerante' else 'agent' end,
          first_user, _main())
  on conflict (id) do nothing;
  perform _log('profiles');
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();

-- ---------- Fonctions appelées par l'application ----------------------
-- Toutes prennent un seul paramètre « p » (jsonb) et renvoient du jsonb.

create or replace function app_bootstrap(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cid bigint;
begin
  select * into me from profiles where id = auth.uid();
  if me.id is null then return jsonb_build_object('me', null); end if;
  if not me.active then return jsonb_build_object('me', to_jsonb(me)); end if;
  cid := _caisse_of(me.id);
  return jsonb_build_object(
    'me', to_jsonb(me) || jsonb_build_object('caisse_id', cid,
            'agence', (select name from agences where id = me.agence_id),
            'is_main_agence', coalesce((select is_main from agences where id = me.agence_id), false),
            'coffre_id', case when me.role <> 'agent' then _coffre_of(me.agence_id) end),
    'accounts', (select coalesce(jsonb_agg(to_jsonb(a) order by a.sort, a.name), '[]') from accounts a
                  where me.role = 'gerante'
                     or (a.active and _acc_in(a, me.agence_id)
                         and (me.role in ('gerant','sous_gerant') or ((a.kind <> 'caisse' or a.agent_id = me.id) and a.kind <> 'coffre')))
                     -- un gérant voit aussi les comptes de l'agence principale où il peut reverser
                     or (me.role in ('gerant','sous_gerant') and a.active and a.agence_id = _main() and a.kind in ('coffre','electronique','banque'))),
    'products', (select coalesce(jsonb_agg(to_jsonb(x) order by x.sort, x.name), '[]') from products x
                  where me.role = 'gerante' or x.active),
    'team', case when me.role = 'gerante' then
              (select coalesce(jsonb_agg(to_jsonb(t) order by t.role desc, t.full_name), '[]') from profiles t)
                 when me.role in ('gerant','sous_gerant') then
              (select coalesce(jsonb_agg(to_jsonb(t) order by t.role desc, t.full_name), '[]') from profiles t where t.agence_id = me.agence_id)
            else '[]'::jsonb end,
    'agences', (select coalesce(jsonb_agg(to_jsonb(g) order by g.is_main desc, g.name), '[]') from agences g
                 where me.role = 'gerante' or g.id = me.agence_id or g.is_main),
    'settings', (select coalesce(jsonb_object_agg(key, value), '{}') from settings)
  );
end $$;

-- Tableau de bord (gérante : tout ; agent : sa caisse + GTP + ses opérations du jour)
create or replace function dashboard(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cid bigint; res jsonb; ag bigint; mgr boolean;
begin
  me := _require(null);
  cid := _caisse_of(me.id);
  ag := _scope(me, p);
  mgr := me.role <> 'agent';
  res := jsonb_build_object(
    'agence_id', ag,
    'balances', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', a.id, 'name', a.name, 'kind', a.kind, 'bank', a.bank, 'agent_id', a.agent_id, 'agence_id', a.agence_id,
        'agence', (select name from agences where id = a.agence_id),
        'low_alert', a.low_alert, 'balance', _bal(a.id),
        'agent', (select full_name from profiles where id = a.agent_id),
        'today_ops', (select count(*) from operations o where o.account_id = a.id and o.op_day = current_date and o.status = 'ok'),
        'last_at', (select max(created_at) from operations o where (o.account_id = a.id or o.account2_id = a.id))
      ) order by a.sort, a.name), '[]')
      from accounts a
      where a.active and _acc_in(a, ag)
        and (mgr or a.kind in ('gtp','electronique') or a.id = cid)),
    'today', (
      select jsonb_build_object(
        'recharges_n', count(*) filter (where kind = 'recharge'),
        'recharges_amount', coalesce(sum(amount) filter (where kind = 'recharge'), 0),
        'commissions', coalesce(sum(commission) filter (where kind = 'recharge'), 0),
        'caisse_n', count(*) filter (where kind = 'caisse'),
        'depenses', coalesce(sum(amount) filter (where kind = 'depense'), 0),
        'ops_n', count(*))
      from operations
      where op_day = current_date and status = 'ok' and (mgr or user_id = me.id) and (ag is null or agence_id = ag)),
    'month_commissions', (
      select coalesce(sum(commission), 0) from operations
      where kind = 'recharge' and status = 'ok' and op_day >= date_trunc('month', current_date)
        and (mgr or user_id = me.id) and (ag is null or agence_id = ag)),
    'recent', (
      select coalesce(jsonb_agg(_op_row(o) order by o.created_at desc, o.id desc), '[]') from (
        select * from operations
        where (mgr or user_id = me.id) and (ag is null or agence_id = ag) and created_at > now() - interval '3 days'
        order by created_at desc, id desc limit 15) o),
    'pending_closings', (select count(*) from closings where status = 'soumise'
      and (mgr or agent_id = me.id) and (ag is null or agence_id = ag)),
    'commissions_to_check', (select count(*) from operations
      where kind = 'recharge' and status = 'ok' and commission_status = 'estimee'
        and (mgr or user_id = me.id) and (ag is null or agence_id = ag)),
    -- Total dû aux fournisseurs (pour qui a le droit « fournisseurs »)
    'fournisseurs_du', case when _can(me, 'fournisseurs') then
      (select coalesce(-sum(least(_bal(a.id), 0)), 0) from accounts a where a.kind = 'fournisseur' and a.active) end,
    -- Soldes entre chaque agence secondaire et l'agence principale
    'liaisons', case when mgr then (
      select coalesce(jsonb_agg(jsonb_build_object('agence_id', g.id, 'agence', g.name, 'balance', _liaison(g.id)) order by g.name), '[]')
      from agences g where not g.is_main and g.active and (me.role = 'gerante' or g.id = me.agence_id)
        and (ag is null or g.id = ag or ag = _main()))
      else '[]'::jsonb end
  );
  if mgr then
    res := res || jsonb_build_object('to_check', (
      select coalesce(jsonb_agg(_op_row(o) order by o.created_at desc, o.id desc), '[]') from (
        select * from operations
        where status = 'ok' and created_at > now() - interval '7 days' and (ag is null or agence_id = ag)
          and (flags like '%doublon%' or flags like '%forcé%'
               or (kind = 'recharge' and commission_status = 'estimee' and commission_auto is not null and abs(commission - commission_auto) >= 1))
        order by created_at desc, id desc limit 20) o));
  end if;
  return res;
end $$;

create or replace function search_cards(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; q text := coalesce(_txt(p, 'q'), ''); b text := _txt(p, 'bank'); lim int := coalesce(_num(p,'limit')::int, 25);
begin
  me := _require(null);
  return (
    select coalesce(jsonb_agg(r), '[]') from (
      select c.*,
        (select jsonb_build_object('at', o.created_at, 'amount', o.amount)
           from operations o where o.card_id = c.id and o.status = 'ok' order by o.created_at desc limit 1) as last_recharge,
        (select count(*) from operations o where o.card_id = c.id and o.status = 'ok') as n_recharges
      from cards c
      where (c.active or me.role = 'gerante')
        and (b is null or c.bank = b)
        and (q = '' or c.card_number like q || '%' or c.holder_name ilike '%' || q || '%' or coalesce(c.phone,'') like '%' || q || '%')
      order by (q <> '' and c.card_number like q || '%') desc,
               (select max(created_at) from operations o where o.card_id = c.id) desc nulls last,
               c.holder_name
      limit lim) r);
end $$;

create or replace function save_card(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cid bigint := _num(p, 'id')::bigint; num text := regexp_replace(coalesce(p->>'card_number',''), '\s', '', 'g');
        nm text := upper(coalesce(_txt(p, 'holder_name'), '')); bk text := upper(coalesce(_txt(p, 'bank'), '')); r cards;
begin
  me := _require('recharge');
  if num = '' then raise exception 'Le numéro de carte est obligatoire.'; end if;
  if nm = '' then raise exception 'Le nom du titulaire est obligatoire.'; end if;
  if bk = '' then raise exception 'Choisissez la banque de la carte.'; end if;
  if exists (select 1 from cards where card_number = num and bank = bk and id is distinct from cid) then
    raise exception 'La carte % (%) existe déjà.', num, bk;
  end if;
  if cid is null then
    insert into cards(card_number, holder_name, bank, gtp_id, phone, note, client_id)
    values (num, nm, bk, _num(p,'gtp_id')::bigint, _txt(p,'phone'), _txt(p,'note'),
            coalesce(_num(p,'client_id')::bigint, _client_for(nm, _txt(p,'phone')))) returning * into r;
  else
    update cards set card_number = num, holder_name = nm, bank = bk,
      gtp_id = _num(p,'gtp_id')::bigint, phone = _txt(p,'phone'), note = _txt(p,'note'),
      client_id = coalesce(_num(p,'client_id')::bigint, client_id, _client_for(nm)),
      active = case when me.role = 'gerante' and p ? 'active' then _bool(p,'active') else active end
    where id = cid returning * into r;
  end if;
  perform _log('cards');
  return to_jsonb(r);
end $$;

-- Opération de caisse (dépôt / retrait Mixx, Flooz, crédit, forfaits, vouchers, impressions...)
create or replace function op_caisse(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; pr products; cash accounts; counter accounts; amt numeric; rec numeric; chg numeric;
        sgn int; oid bigint; cnt_id bigint;
begin
  me := _require('caisse');
  select * into pr from products where id = _num(p,'product_id')::bigint;
  if pr.id is null or not pr.active then raise exception 'Produit introuvable ou désactivé.'; end if;
  rec := _num(p, 'received'); chg := coalesce(_num(p, 'change_given'), 0);
  amt := coalesce(_num(p, 'amount'), rec - chg);
  if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  if rec is not null and rec - chg <> amt then raise exception 'Reçu − monnaie rendue ne correspond pas au montant.'; end if;
  cash := _check_use(me, coalesce(_num(p,'cash_account_id')::bigint, _caisse_of(me.id)));
  cnt_id := coalesce(_num(p,'counter_account_id')::bigint, pr.counter_account_id);
  if cnt_id is not null then
    counter := _check_use(me, cnt_id);
    if counter.id = cash.id then raise exception 'Le compte d''encaissement et le compte électronique doivent être différents.'; end if;
  end if;
  sgn := case pr.direction when 'entree' then 1 else -1 end;
  if sgn = -1 then perform _check_funds(cash, amt); end if;
  if sgn = 1 and counter.id is not null then perform _check_funds(counter, amt); end if;

  insert into operations(user_id, kind, product_id, account_id, account2_id, amount, received, change_given, details, client_id, receipt_id)
  values (me.id, 'caisse', pr.id, cash.id, counter.id, amt, rec, case when rec is null then null else chg end, _txt(p,'details'),
          _num(p,'client_id')::bigint, _num(p,'receipt_id')::bigint)
  returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, cash.id, sgn * amt);
  if counter.id is not null then
    insert into movements(operation_id, account_id, amount) values (oid, counter.id, -sgn * amt);
  end if;
  -- Vente de cartes physiques : le stock diminue (entrée : vente ; sortie : reprise).
  if pr.card_type_id is not null then
    insert into stock_moves(user_id, agence_id, card_type_id, qty, kind, operation_id)
      values (me.id, coalesce(me.agence_id, _main()), pr.card_type_id, -sgn * greatest(coalesce(_num(p,'qty'), 1), 1)::int, 'vente', oid);
  end if;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(cash.id));
end $$;

-- Recharge de carte prépayée
create or replace function op_recharge(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; g accounts; c cards; pay accounts; amt numeric; com numeric; auto numeric; bal numeric;
        dup record; oid bigint; fl text := '';
begin
  me := _require('recharge');
  select * into g from accounts where id = _num(p,'gtp_id')::bigint and kind = 'gtp';
  if g.id is null or not g.active then raise exception 'Choisissez un compte GTP actif.'; end if;
  select * into c from cards where id = _num(p,'card_id')::bigint;
  if c.id is null then raise exception 'Choisissez la carte du client.'; end if;
  amt := _num(p, 'amount');
  if amt is null or amt <= 0 then raise exception 'Montant de recharge invalide.'; end if;
  auto := _commission(g.id, amt);
  com := coalesce(_num(p, 'commission'), auto);
  if com < 0 then raise exception 'Commission invalide.'; end if;
  pay := _check_use(me, coalesce(_num(p,'pay_account_id')::bigint, _caisse_of(me.id)));

  if not _bool(p, 'force_duplicate') then
    select o.id, o.created_at, pf.full_name as agent into dup
    from operations o left join profiles pf on pf.id = o.user_id
    where o.kind = 'recharge' and o.status = 'ok' and o.card_id = c.id and o.amount = amt
      and o.created_at > now() - interval '24 hours'
    order by o.created_at desc limit 1;
    if dup.id is not null then
      return jsonb_build_object('ok', false, 'duplicate',
        jsonb_build_object('id', dup.id, 'created_at', dup.created_at, 'agent', dup.agent));
    end if;
  else
    fl := 'doublon confirmé';
  end if;

  bal := _bal(g.id);
  if bal - amt + com < 0 and not g.allow_negative then
    if me.role = 'gerante' and _bool(p, 'force_balance') then
      fl := trim(both ' ,' from fl || ', solde GTP négatif forcé');
    else
      return jsonb_build_object('ok', false, 'insufficient',
        jsonb_build_object('balance', bal, 'needed', amt - com, 'account', g.name));
    end if;
  end if;
  if com <> auto then fl := trim(both ' ,' from fl || ', commission modifiée'); end if;

  insert into operations(user_id, kind, card_id, account_id, account2_id, amount, commission, commission_auto, details, flags, client_id, receipt_id, commission_status)
  values (me.id, 'recharge', c.id, g.id, pay.id, amt, com, auto, _txt(p,'details'), fl,
          coalesce(_num(p,'client_id')::bigint, c.client_id), _num(p,'receipt_id')::bigint, 'estimee')
  returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, g.id, -amt + com), (oid, pay.id, amt);
  update cards set gtp_id = g.id where id = c.id and gtp_id is null;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(g.id));
end $$;

-- Sortie / dépense
create or replace function op_depense(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; a accounts; amt numeric := _num(p,'amount'); motif text := _txt(p,'details'); oid bigint;
begin
  me := _require(null);
  if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  if motif is null then raise exception 'Indiquez le motif de la dépense.'; end if;
  a := _check_use(me, coalesce(_num(p,'account_id')::bigint, _caisse_of(me.id)));
  if a.kind = 'gtp' and me.role <> 'gerante' then raise exception 'Compte non autorisé.'; end if;
  perform _check_funds(a, amt);
  insert into operations(user_id, kind, account_id, amount, details, category)
  values (me.id, 'depense', a.id, amt, motif, _txt(p,'category')) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt);
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(a.id));
end $$;

-- Un compte de « mon » agence (pour un gérant / sous-gérant) : de son agence, ou commun s'il est à la principale.
create or replace function _mine(me profiles, a accounts) returns boolean
language sql stable as $$
  select coalesce(me.role = 'gerante' or a.agence_id = me.agence_id or (a.agence_id is null and me.agence_id = _main()), false)
$$;

-- Approvisionnement d'un compte (GTP, Mixx, Flooz…), éventuellement acheté chez un fournisseur.
-- p = {gtp_id (compte approvisionné), amount, source_id?, fournisseur_id?, details}
-- source = un fournisseur → achat à crédit (on lui doit) ; source = coffre/caisse/banque → payé comptant.
create or replace function op_approvisionnement(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; g accounts; src accounts; f accounts; amt numeric := _num(p,'amount'); oid bigint;
begin
  me := _require_perm('appro');
  select * into g from accounts where id = _num(p,'gtp_id')::bigint;
  if g.id is null or g.kind = 'fournisseur' then raise exception 'Choisissez le compte à approvisionner.'; end if;
  if not _mine(me, g) then raise exception 'Vous ne pouvez approvisionner que les comptes de votre agence.'; end if;
  if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  if _num(p,'fournisseur_id') is not null then
    select * into f from accounts where id = _num(p,'fournisseur_id')::bigint and kind = 'fournisseur';
    if f.id is null then raise exception 'Fournisseur introuvable.'; end if;
  end if;
  if _num(p,'source_id') is not null then
    select * into src from accounts where id = _num(p,'source_id')::bigint;
    if src.id is null or src.id = g.id then raise exception 'La source doit être différente du compte approvisionné.'; end if;
    if src.kind = 'fournisseur' then
      f := src;                                    -- achat à crédit chez ce fournisseur
    else
      if not _mine(me, src) then raise exception 'L''argent doit venir d''un compte de votre agence.'; end if;
      perform _check_funds(src, amt);
    end if;
  end if;
  insert into operations(user_id, kind, account_id, account2_id, amount, details, fournisseur_id)
  values (me.id, 'approvisionnement', g.id, src.id, amt, _txt(p,'details'), f.id) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, g.id, amt);
  if src.id is not null then insert into movements(operation_id, account_id, amount) values (oid, src.id, -amt); end if;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(g.id));
end $$;

-- Transfert entre deux comptes (gérante) : versement en banque, réapprovisionnement Mixx, fond de caisse...
create or replace function op_transfert(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; a accounts; b accounts; amt numeric := _num(p,'amount'); oid bigint;
begin
  me := _require('manager');
  if me.role = 'sous_gerant' and not _can(me, 'appro') then raise exception 'Vous n''avez pas le droit de faire des transferts.'; end if;
  select * into a from accounts where id = _num(p,'from_id')::bigint;
  select * into b from accounts where id = _num(p,'to_id')::bigint;
  if a.id is null or b.id is null or a.id = b.id then raise exception 'Choisissez deux comptes différents.'; end if;
  if a.kind = 'fournisseur' or b.kind = 'fournisseur' then raise exception 'Pour un fournisseur, utilisez « Payer un fournisseur » ou « Approvisionner ».'; end if;
  -- Un gérant d'agence transfère depuis un compte de son agence, vers son agence ou l'agence principale.
  if me.role in ('gerant','sous_gerant') then
    if a.agence_id is distinct from me.agence_id then
      raise exception 'Vous ne pouvez transférer que depuis un compte de votre agence.';
    end if;
    if b.agence_id is distinct from me.agence_id and coalesce(b.agence_id, _main()) <> _main() then
      raise exception 'Destination non autorisée : votre agence ou l''agence principale seulement.';
    end if;
  end if;
  if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  perform _check_funds(a, amt);
  insert into operations(user_id, kind, account_id, account2_id, amount, details)
  values (me.id, 'transfert', a.id, b.id, amt, _txt(p,'details')) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt), (oid, b.id, amt);
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid);
end $$;

-- Ajustement de solde avec motif obligatoire (gérante). amount positif ou négatif.
-- Si « target » est fourni, l'ajustement amène le solde exactement à cette valeur.
create or replace function op_ajustement(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; a accounts; amt numeric; motif text := _txt(p,'details'); oid bigint;
begin
  me := _require_perm('ajust');
  select * into a from accounts where id = _num(p,'account_id')::bigint;
  if a.id is null then raise exception 'Compte introuvable.'; end if;
  if me.role in ('gerant','sous_gerant') and a.agence_id is distinct from me.agence_id then
    raise exception 'Vous ne pouvez ajuster que les comptes de votre agence.';
  end if;
  if motif is null then raise exception 'Le motif de l''ajustement est obligatoire.'; end if;
  if _num(p,'target') is not null then amt := _num(p,'target') - _bal(a.id); else amt := _num(p,'amount'); end if;
  if amt is null or amt = 0 then return jsonb_build_object('ok', true, 'id', null, 'balance', _bal(a.id), 'unchanged', true); end if;
  insert into operations(user_id, kind, account_id, amount, details)
  values (me.id, 'ajustement', a.id, amt, motif) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, amt);
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(a.id));
end $$;

-- Annulation tracée : l'opération reste visible, barrée, avec des mouvements inverses.
-- Un agent peut annuler sa propre opération dans les 30 minutes (hors clôture) ; sinon la gérante.
create or replace function op_annuler(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; o operations; motif text := _txt(p,'reason');
begin
  me := _require(null);
  select * into o from operations where id = _num(p,'id')::bigint for update;
  if o.id is null then raise exception 'Opération introuvable.'; end if;
  if o.status <> 'ok' then raise exception 'Cette opération est déjà annulée.'; end if;
  if o.partner_op_id is not null then
    raise exception 'Cette opération appartient au dossier partenaire % : annulez-la depuis ce dossier.', (select ref from partner_ops where id = o.partner_op_id);
  end if;
  if motif is null then raise exception 'Indiquez le motif de l''annulation.'; end if;
  if me.role in ('gerant','sous_gerant') then
    if o.agence_id is distinct from me.agence_id then
      raise exception 'Cette opération appartient à une autre agence.';
    end if;
  elsif me.role <> 'gerante' then
    if o.user_id is distinct from me.id or o.created_at < now() - interval '30 minutes' or o.closing_id is not null
       or o.kind not in ('caisse','recharge','depense','avoir') then
      raise exception 'Seul(e) le gérant ou la gérante peut annuler cette opération (délai de 30 minutes dépassé ou caisse clôturée).';
    end if;
  end if;
  update operations set status = 'annulee', cancelled_at = now(), cancelled_by = me.id, cancel_reason = motif where id = o.id;
  insert into movements(operation_id, account_id, amount, reversal)
    select o.id, account_id, -amount, true from movements where operation_id = o.id and not reversal;
  perform _log('operations');
  return jsonb_build_object('ok', true);
end $$;

create or replace function list_operations(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; d1 date := coalesce(_txt(p,'from')::date, current_date); d2 date := coalesce(_txt(p,'to')::date, current_date);
        uid uuid := _txt(p,'user_id')::uuid; k text := _txt(p,'kind'); acc bigint := _num(p,'account_id')::bigint;
        q text := _txt(p,'q'); lim int := least(coalesce(_num(p,'limit')::int, 300), 20000); ag bigint;
begin
  me := _require(null);
  if me.role = 'agent' then uid := me.id; end if;
  ag := _scope(me, p);
  return (
    select coalesce(jsonb_agg(_op_row(o) order by o.created_at desc, o.id desc), '[]') from (
      select * from operations o
      where o.op_day between d1 and d2
        and (uid is null or o.user_id = uid)
        and (ag is null or o.agence_id = ag)
        and (k is null or o.kind = k)
        and (acc is null or o.account_id = acc or o.account2_id = acc)
        and (_num(p,'client_id') is null or o.client_id = _num(p,'client_id')::bigint)
        and (_num(p,'receipt_id') is null or o.receipt_id = _num(p,'receipt_id')::bigint)
        and (_num(p,'fournisseur_id') is null or o.fournisseur_id = _num(p,'fournisseur_id')::bigint)
        and (_txt(p,'commission_status') is null or o.commission_status = _txt(p,'commission_status'))
        and (_bool(p,'include_cancelled') or o.status = 'ok' or _txt(p,'include_cancelled') is null)
        and (q is null or o.details ilike '%'||q||'%'
             or exists (select 1 from cards c where c.id = o.card_id and (c.card_number like q||'%' or c.holder_name ilike '%'||q||'%')))
      order by o.created_at desc, o.id desc limit lim) o);
end $$;

-- Vérification de la commission d'une recharge, d'après le rapport du GTP.
-- p = {id, commission}. Un agent vérifie ses propres recharges ; la gérante, toutes.
-- La différence est portée sur le solde GTP, à la date d'origine de la recharge.
create or replace function verify_commission(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; o operations; com numeric := _num(p,'commission'); diff numeric;
begin
  me := _require('recharge');
  select * into o from operations where id = _num(p,'id')::bigint for update;
  if o.id is null or o.kind <> 'recharge' then raise exception 'Recharge introuvable.'; end if;
  if o.status <> 'ok' then raise exception 'Cette recharge est annulée.'; end if;
  if me.role = 'agent' and o.user_id is distinct from me.id then
    raise exception 'Vous ne pouvez vérifier que vos propres recharges.';
  end if;
  if me.role in ('gerant','sous_gerant') and o.agence_id is distinct from me.agence_id then
    raise exception 'Cette recharge appartient à une autre agence.';
  end if;
  if com is null or com < 0 then raise exception 'Commission invalide.'; end if;
  diff := com - o.commission;
  if diff <> 0 then
    insert into movements(operation_id, account_id, amount, created_at) values (o.id, o.account_id, diff, now());
  end if;
  update operations set
    commission_before = case when diff <> 0 and commission_before is null then commission else commission_before end,
    commission = com, commission_status = 'verifiee', commission_verified_by = me.id, commission_verified_at = now(),
    flags = case when diff <> 0 and flags not like '%commission corrigée%'
                 then trim(both ' ,' from flags || ', commission corrigée') else flags end
  where id = o.id;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'diff', diff, 'balance', _bal(o.account_id));
end $$;

-- ---------- Fournisseurs ----------------------------------------------------
-- Un fournisseur est un compte de type « fournisseur », commun à toutes les agences.
-- Achat à crédit : le compte approvisionné monte, le fournisseur descend (on lui doit).
-- Paiement : l'argent sort du coffre / de la banque…, le fournisseur remonte vers zéro.

create or replace function save_fournisseur(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; fid bigint := _num(p,'id')::bigint; r accounts;
begin
  me := _require_perm('fournisseurs');
  if _txt(p,'name') is null then raise exception 'Le nom du fournisseur est obligatoire.'; end if;
  if exists (select 1 from accounts where kind = 'fournisseur' and upper(name) = upper(_txt(p,'name')) and id is distinct from fid) then
    raise exception 'Ce fournisseur existe déjà.';
  end if;
  if fid is null then
    insert into accounts(name, kind, phone, note, allow_negative, sort)
    values (_txt(p,'name'), 'fournisseur', _txt(p,'phone'), _txt(p,'note'), true, 200) returning * into r;
  else
    update accounts set name = _txt(p,'name'), phone = _txt(p,'phone'), note = _txt(p,'note'),
      active = coalesce((p->>'active')::boolean, active)
    where id = fid and kind = 'fournisseur' returning * into r;
    if r.id is null then raise exception 'Fournisseur introuvable.'; end if;
  end if;
  perform _log('accounts');
  return to_jsonb(r);
end $$;

create or replace function list_fournisseurs(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles;
begin
  me := _require_perm('fournisseurs');
  return (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', a.id, 'name', a.name, 'phone', a.phone, 'note', a.note, 'active', a.active,
      'du', -_bal(a.id),
      'achats_mois', (select coalesce(sum(o.amount), 0) from operations o
                      where o.fournisseur_id = a.id and o.kind = 'approvisionnement' and o.status = 'ok'
                        and o.op_day >= date_trunc('month', current_date)),
      'last_at', (select max(o.created_at) from operations o where o.fournisseur_id = a.id)
    ) order by a.active desc, a.name), '[]')
    from accounts a where a.kind = 'fournisseur');
end $$;

-- Paiement d'un fournisseur. p = {fournisseur_id, from_id, amount, details}
create or replace function op_paiement_fournisseur(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; f accounts; a accounts; amt numeric := _num(p,'amount'); oid bigint;
begin
  me := _require_perm('fournisseurs');
