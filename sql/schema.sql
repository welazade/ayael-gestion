create or replace function _pop_insert(d partner_ops, me profiles, k text, stg text, a1 bigint, a2 bigint, amt numeric,
                                       com numeric, idem text, det text, f bigint default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare oid bigint;
begin
  insert into operations(user_id, kind, account_id, account2_id, amount, commission, details, client_id, partner_op_id, stage, idem_key, fournisseur_id)
