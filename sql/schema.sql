-- Recherche par nom (tous les mots, dans n'importe quel ordre), téléphone ou n° de carte.
create or replace function search_clients(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; q text := upper(coalesce(_txt(p,'q'), '')); lim int := coalesce(_num(p,'limit')::int, 15);
begin
  me := _require(null);
  return (
    select coalesce(jsonb_agg(x), '[]') from (
      select cl.*,
        (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'card_number', c.card_number, 'bank', c.bank,
                 'holder_name', c.holder_name, 'gtp_id', c.gtp_id) order by c.bank, c.card_number), '[]')
           from cards c where c.client_id = cl.id and c.active) as cards,
        (select max(created_at) from operations o where o.client_id = cl.id and o.status = 'ok') as last_at,
        (select count(*) from operations o where o.client_id = cl.id and o.status = 'ok') as n_ops
      from clients cl
      where cl.active and (
        q = ''
        or not exists (select 1 from unnest(string_to_array(q, ' ')) w where w <> '' and upper(cl.name) not like '%' || w || '%')
        or replace(coalesce(cl.phone, ''), ' ', '') like '%' || replace(q, ' ', '') || '%'
        or exists (select 1 from cards c where c.client_id = cl.id and c.card_number like replace(q, ' ', '') || '%'))
      order by (q <> '' and upper(cl.name) like q || '%') desc,
               (select max(created_at) from operations o where o.client_id = cl.id) desc nulls last,
               cl.name
      limit lim) x);
end $$;

create or replace function save_client(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cid bigint := _num(p,'id')::bigint; nm text := upper(coalesce(_txt(p,'name'), '')); r clients;
begin
  me := _require(null);
  if nm = '' then raise exception 'Le nom du client est obligatoire.'; end if;
  if cid is null then
    insert into clients(name, phone, note) values (nm, _txt(p,'phone'), _txt(p,'note')) returning * into r;
  else
    update clients set name = nm, phone = _txt(p,'phone'), note = _txt(p,'note'),
      active = case when me.role = 'gerante' and p ? 'active' then _bool(p,'active') else active end
    where id = cid returning * into r;
    if r.id is null then raise exception 'Client introuvable.'; end if;
  end if;
  perform _log('clients');
  return to_jsonb(r) || jsonb_build_object('cards', (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'card_number', c.card_number,
            'bank', c.bank, 'holder_name', c.holder_name, 'gtp_id', c.gtp_id)), '[]') from cards c where c.client_id = r.id and c.active));
end $$;

-- Vente / passage en caisse : plusieurs produits pour un même client, un seul reçu.
-- p = { client_id | client_name, pay_account_id, received, lines: [
--        {type:'caisse', product_id, amount, details, counter_account_id}
--        {type:'recharge', card_id, gtp_id, amount, commission, details} ],
--       force_duplicate, force_balance }
-- Vérifie d'abord tout (doublons, soldes GTP) sans rien enregistrer ; puis enregistre tout, ou rien.
create or replace function op_vente(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; ln jsonb; cl clients; rid bigint; pay bigint; tot numeric := 0; warn jsonb := '[]';
        g accounts; c cards; pr products; amt numeric; com numeric; dup record; r jsonb; bals jsonb := '{}'; after numeric; rec numeric;
begin
  me := _require(null);
  if jsonb_typeof(p->'lines') is distinct from 'array' or jsonb_array_length(p->'lines') = 0 then
    raise exception 'Ajoutez au moins un produit.';
  end if;
  if _num(p,'client_id') is not null then
    select * into cl from clients where id = _num(p,'client_id')::bigint;
    if cl.id is null then raise exception 'Client introuvable.'; end if;
  end if;
  pay := coalesce(_num(p,'pay_account_id')::bigint, _caisse_of(me.id));

  for ln in select * from jsonb_array_elements(p->'lines') loop
    amt := _num(ln, 'amount');
    if ln->>'type' = 'recharge' then
      select * into g from accounts where id = _num(ln,'gtp_id')::bigint and kind = 'gtp';
      select * into c from cards where id = _num(ln,'card_id')::bigint;
      if g.id is null or c.id is null then raise exception 'Recharge incomplète : choisissez la carte et le compte GTP.'; end if;
      if amt is null or amt <= 0 then raise exception 'Montant de recharge invalide.'; end if;
      com := coalesce(_num(ln,'commission'), _commission(g.id, amt));
      if not _bool(p,'force_duplicate') then
        select o.created_at, pf.full_name as agent into dup
        from operations o left join profiles pf on pf.id = o.user_id
        where o.kind = 'recharge' and o.status = 'ok' and o.card_id = c.id and o.amount = amt
          and o.created_at > now() - interval '24 hours'
        order by o.created_at desc limit 1;
        if found then
          warn := warn || jsonb_build_object('type', 'duplicate', 'card', c.card_number, 'holder', c.holder_name,
                                             'amount', amt, 'created_at', dup.created_at, 'agent', dup.agent);
        end if;
      end if;
      after := coalesce((bals->>(g.id::text))::numeric, _bal(g.id)) - amt + com;
      bals := bals || jsonb_build_object(g.id::text, after);
      if after < 0 and not g.allow_negative and not (me.role = 'gerante' and _bool(p,'force_balance')) then
        warn := warn || jsonb_build_object('type', 'insufficient', 'account', g.name, 'balance', _bal(g.id), 'after', after);
      end if;
      tot := tot + amt;
    elsif ln->>'type' = 'caisse' then
      select * into pr from products where id = _num(ln,'product_id')::bigint;
      if pr.id is null or not pr.active then raise exception 'Produit introuvable.'; end if;
      if amt is null or amt <= 0 then raise exception 'Montant invalide pour « % ».', pr.name; end if;
      tot := tot + case pr.direction when 'entree' then amt else -amt end;
    else
      raise exception 'Ligne inconnue.';
    end if;
  end loop;

  if jsonb_array_length(warn) > 0 then
    return jsonb_build_object('ok', false, 'warnings', warn,
      'can_force_balance', me.role = 'gerante');
  end if;

  rec := _num(p, 'received');
  if tot <= 0 then rec := null; end if;
  if rec is not null and rec < tot then raise exception 'Le montant reçu est inférieur au total à payer.'; end if;

  insert into receipts(user_id, client_id, client_name, total, received, change_given, pay_account_id)
  values (me.id, cl.id, coalesce(cl.name, upper(_txt(p,'client_name'))), tot, rec, rec - tot, pay)
  returning id into rid;

  for ln in select * from jsonb_array_elements(p->'lines') loop
    if ln->>'type' = 'recharge' then
      r := op_recharge(ln || jsonb_build_object('pay_account_id', pay, 'client_id', cl.id, 'receipt_id', rid,
                                                'force_duplicate', _bool(p,'force_duplicate'), 'force_balance', _bool(p,'force_balance')));
      if not coalesce((r->>'ok')::boolean, false) then
        if r ? 'duplicate' then raise exception 'La même recharge (même carte, même montant) figure deux fois.'; end if;
        raise exception 'Solde GTP insuffisant.';
      end if;
    else
      select * into pr from products where id = _num(ln,'product_id')::bigint;
      r := op_caisse(jsonb_build_object('product_id', pr.id, 'amount', _num(ln,'amount'), 'details', ln->'details',
                                        'counter_account_id', ln->'counter_account_id', 'client_id', cl.id, 'receipt_id', rid,
                                        'cash_account_id', case when pr.direction = 'entree' then pay end));
    end if;
  end loop;
  return jsonb_build_object('ok', true, 'receipt_id', rid, 'total', tot);
end $$;

create or replace function get_receipt(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; r receipts;
begin
  me := _require(null);
  select * into r from receipts where id = _num(p,'id')::bigint;
  if r.id is null then raise exception 'Reçu introuvable.'; end if;
  return to_jsonb(r) || jsonb_build_object(
    'agent', (select full_name from profiles where id = r.user_id),
    'client_phone', (select phone from clients where id = r.client_id),
    'pay_account', (select name from accounts where id = r.pay_account_id),
    'pay_kind', (select kind from accounts where id = r.pay_account_id),
    'lines', (select coalesce(jsonb_agg(_op_row(o) order by o.id), '[]') from operations o where o.receipt_id = r.id),
    'company', (select value from settings where key = 'company'));
end $$;

create or replace function save_settings(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; k text := _txt(p,'key');
begin
  me := _require('gerante');
  if k is null or p->'value' is null then raise exception 'Réglage invalide.'; end if;
  insert into settings(key, value) values (k, p->'value')
  on conflict (key) do update set value = excluded.value;
  perform _log('settings');
  return jsonb_build_object('ok', true);
end $$;

