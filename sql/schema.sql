-- Ajustement de solde avec motif obligatoire (gérante). amount positif ou négatif.
-- Si « target » est fourni, l'ajustement amène le solde exactement à cette valeur.
create or replace function op_ajustement(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; a accounts; amt numeric; motif text := _txt(p,'details'); oid bigint;
begin
  me := _require('gerante');
  select * into a from accounts where id = _num(p,'account_id')::bigint;
  if a.id is null then raise exception 'Compte introuvable.'; end if;
  if motif is null then raise exception 'Le motif de l''ajustement est obligatoire.'; end if;
  if _num(p,'target') is not null then amt := _num(p,'target') - _bal(a.id); else amt := _num(p,'amount'); end if;
