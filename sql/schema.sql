create or replace function closing_preview(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; uid uuid; acc bigint; last closings; since timestamptz;
begin
  me := _require(null);
  uid := case when me.role = 'gerante' and _txt(p,'agent_id') is not null then _txt(p,'agent_id')::uuid else me.id end;
  acc := _caisse_of(uid);
  select * into last from closings where agent_id = uid and status <> 'rejetee' order by created_at desc, id desc limit 1;
  since := coalesce(last.created_at, '-infinity'::timestamptz);
  return jsonb_build_object(
    'account_id', acc,
    'expected', _bal(acc),
    'last', to_jsonb(last),
    'pending', exists (select 1 from closings where agent_id = uid and status = 'soumise'),
    'summary', (
      select coalesce(jsonb_agg(jsonb_build_object('label', label, 'n', n, 'in', vin, 'out', vout) order by label), '[]') from (
        select coalesce(pr.name, case o.kind when 'recharge' then 'Recharges ' || a.name when 'depense' then 'Dépenses'
                                    else initcap(o.kind) end) as label,
               count(distinct o.id) as n,
               coalesce(sum(m.amount) filter (where m.amount > 0), 0) as vin,
               coalesce(-sum(m.amount) filter (where m.amount < 0), 0) as vout
        from operations o
        join movements m on m.operation_id = o.id and m.account_id = acc and not m.reversal
        left join products pr on pr.id = o.product_id
        left join accounts a on a.id = o.account_id
        where o.status = 'ok' and o.created_at > since
        group by 1) s)
  );
end $$;

create or replace function closing_submit(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; acc bigint; exp numeric; cnt numeric := _num(p,'counted'); hd numeric := coalesce(_num(p,'handed'), 0); cid bigint;
begin
  me := _require(null);
  if cnt is null or cnt < 0 then raise exception 'Indiquez le montant compté.'; end if;
  if hd < 0 or hd > cnt then raise exception 'Le montant remis doit être entre 0 et le montant compté.'; end if;
  if exists (select 1 from closings where agent_id = me.id and status = 'soumise') then
    raise exception 'Une clôture attend déjà la validation de la gérante.';
  end if;
  acc := _caisse_of(me.id);
  exp := _bal(acc);
  insert into closings(agent_id, account_id, expected, counted, gap, handed, note)
  values (me.id, acc, exp, cnt, cnt - exp, hd, _txt(p,'note')) returning id into cid;
  update operations set closing_id = cid where user_id = me.id and closing_id is null;
  perform _log('closings');
  return jsonb_build_object('ok', true, 'id', cid, 'expected', exp, 'gap', cnt - exp);
end $$;

create or replace function closing_validate(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; c closings; oid bigint; cof bigint; nm text;
begin
  me := _require('gerante');
  select * into c from closings where id = _num(p,'id')::bigint for update;
  if c.id is null then raise exception 'Clôture introuvable.'; end if;
  if c.status <> 'soumise' then raise exception 'Cette clôture a déjà été traitée.'; end if;
  select full_name into nm from profiles where id = c.agent_id;
  if not _bool(p, 'accept') then
    update closings set status = 'rejetee', validated_by = me.id, validated_at = now(), manager_note = _txt(p,'note') where id = c.id;
    update operations set closing_id = null where closing_id = c.id;
  else
    if c.gap <> 0 then
      insert into operations(user_id, kind, account_id, amount, details, closing_id)
      values (me.id, 'ajustement', c.account_id, c.gap,
              'Écart de clôture du ' || to_char(c.day, 'DD/MM/YYYY') || ' (' || nm || ')', c.id) returning id into oid;
      insert into movements(operation_id, account_id, amount) values (oid, c.account_id, c.gap);
    end if;
    if c.handed > 0 then
      cof := _coffre();
      insert into operations(user_id, kind, account_id, account2_id, amount, details, closing_id)
      values (me.id, 'cloture', c.account_id, cof, c.handed,
              'Remise de caisse du ' || to_char(c.day, 'DD/MM/YYYY') || ' (' || nm || ')', c.id) returning id into oid;
      insert into movements(operation_id, account_id, amount) values (oid, c.account_id, -c.handed), (oid, cof, c.handed);
    end if;
    update closings set status = 'validee', validated_by = me.id, validated_at = now(), manager_note = _txt(p,'note') where id = c.id;
  end if;
  perform _log('closings');
  return jsonb_build_object('ok', true);
end $$;

