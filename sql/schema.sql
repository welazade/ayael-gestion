-- ---------- Sécurité Supabase (ignoré hors Supabase) -----------------------

alter table profiles   enable row level security;
alter table accounts   enable row level security;
alter table products   enable row level security;
alter table cards      enable row level security;
alter table closings   enable row level security;
alter table operations enable row level security;
alter table movements  enable row level security;
alter table change_log enable row level security;
alter table clients    enable row level security;
alter table receipts   enable row level security;
alter table settings   enable row level security;

do $$
declare f record;
begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    -- Aucun accès direct aux tables : tout passe par les fonctions ci-dessus.
    execute 'revoke all on profiles, accounts, products, cards, closings, operations, movements, change_log, clients, receipts, settings from anon, authenticated';
    execute 'grant select on change_log to authenticated';
    if not exists (select 1 from pg_policies where tablename = 'change_log' and policyname = 'change_log_read') then
      execute 'create policy change_log_read on change_log for select to authenticated using (true)';
    end if;
    -- Fonctions : seules celles sans « _ » au début sont appelables par l'application.
    for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where n.nspname = 'public' and p.proname in (
               '_num','_txt','_bool','_log','_require','_bal','_caisse_of','_coffre','_commission','_check_use','_check_funds','_op_row',
               'handle_new_user','app_bootstrap','dashboard','search_cards','save_card','op_caisse','op_recharge','op_depense',
               'op_approvisionnement','op_transfert','op_ajustement','op_annuler','list_operations','closing_preview',
               'closing_submit','closing_validate','list_closings','report','save_account','save_product','save_profile','import_cards',
               '_client_for','search_clients','save_client','op_vente','get_receipt','save_settings')
    loop
      execute format('revoke execute on function %s from public, anon', f.sig);
      if left(f.proname, 1) = '_' or f.proname = 'handle_new_user' then
        execute format('revoke execute on function %s from authenticated', f.sig);
      else
        execute format('grant execute on function %s to authenticated', f.sig);
      end if;
    end loop;
  end if;
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'change_log') then
    execute 'alter publication supabase_realtime add table change_log';
  end if;
end $$;
