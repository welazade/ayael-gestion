-- ---------- Crédits clients : fonctions --------------------------------------

-- Position d'un client : positif = il nous doit ; négatif = avance disponible.
create or replace function _client_pos(cid bigint) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(m.amount), 0) from movements m
  join operations o on o.id = m.operation_id join accounts a on a.id = m.account_id
  where a.kind = 'avoir' and o.client_id = cid
$$;

-- Ventes à crédit d'un client avec leur reste à payer.
-- Les affectations choisies s'appliquent d'abord ; le reste des paiements règle les dettes les plus anciennes.
create or replace function _client_credit_state(cid bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d numeric := greatest(_client_pos(cid), 0); r record; cap numeric; rest numeric; res jsonb := '[]';
begin
  -- On remplit la dette restante en partant des ventes les plus récentes (les plus anciennes sont réglées en premier).
  for r in
    select c.*, coalesce((select sum(a.amount) from credit_allocs a join operations o on o.id = a.operation_id
                          where a.credit_id = c.id and o.status = 'ok'), 0) as manual
    from client_credits c join operations o on o.id = c.operation_id
    where c.client_id = cid and o.status = 'ok'
    order by c.created_at desc, c.id desc
  loop
    cap := greatest(r.amount - r.manual, 0);
    rest := least(cap, d);
    d := d - rest;
    res := jsonb_build_object('id', r.id, 'created_at', r.created_at, 'amount', r.amount, 'paid', r.amount - rest, 'remaining', rest,
             'due_date', r.due_date, 'label', r.label, 'ref', r.ref, 'receipt_id', r.receipt_id, 'partner_op_id', r.partner_op_id,
             'status', case when rest <= 0 then 'payee' when rest >= r.amount then 'non_payee' else 'partielle' end,
             'days_late', case when rest > 0 and r.due_date < current_date then current_date - r.due_date else 0 end) || res;
  end loop;
  return res;   -- du plus ancien au plus récent
end $$;

-- Vérifie l'autorisation et le plafond. Renvoie un avertissement (texte) si le plafond est dépassé, null sinon.
create or replace function _credit_check(me profiles, cl clients, amt numeric, force boolean) returns text
language plpgsql stable security definer set search_path = public as $$
declare cur numeric;
begin
  if cl.id is null then raise exception 'Choisissez le client (fiche enregistrée) pour vendre à crédit.'; end if;
  if not cl.credit_allowed then raise exception 'Le client % n''est pas autorisé à acheter à crédit.', cl.name; end if;
  cur := greatest(_client_pos(cl.id), 0);
  if cur + amt > cl.credit_limit then
    if force and me.role <> 'agent' then return null; end if;
    return format('Plafond dépassé : %s doit déjà %s F, plafond %s F. Avec cette vente : %s F.', cl.name,
      replace(to_char(cur, 'FM999,999,999,990'), ',', ' '), replace(to_char(cl.credit_limit, 'FM999,999,999,990'), ',', ' '),
      replace(to_char(cur + amt, 'FM999,999,999,990'), ',', ' '));
  end if;
  return null;
end $$;

-- Crée la dette d'une vente à crédit (opération + ligne de créance). pay = compte qui n'a pas reçu l'argent (vente au guichet), ou null.
create or replace function _credit_create(me profiles, cl clients, amt numeric, due date, pay bigint, rid bigint, pop bigint, lbl text, rf text)
returns bigint
language plpgsql security definer set search_path = public as $$
declare av bigint; oid bigint;
begin
  select id into av from accounts where kind = 'avoir' order by id limit 1;
  insert into operations(user_id, kind, account_id, account2_id, amount, details, category, client_id, receipt_id, partner_op_id, stage)
  values (me.id, 'avoir', coalesce(pay, av), av, amt, 'Vente à crédit · ' || coalesce(lbl, '') || ' · échéance ' || to_char(due, 'DD/MM/YYYY'),
          'credit', cl.id, rid, pop, case when pop is not null then 'credit' end)
  returning id into oid;
  if pay is not null then insert into movements(operation_id, account_id, amount) values (oid, pay, -amt); end if;
  insert into movements(operation_id, account_id, amount) values (oid, av, amt);
  insert into client_credits(user_id, client_id, operation_id, receipt_id, partner_op_id, amount, due_date, label, ref)
  values (me.id, cl.id, oid, rid, pop, amt, due, lbl, rf);
  return oid;
end $$;

-- Réglages de crédit d'un client (responsables).
create or replace function save_client_credit(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; r clients;
begin
  me := _require('manager');
  update clients set credit_allowed = _bool(p,'credit_allowed'), credit_limit = greatest(coalesce(_num(p,'credit_limit'), 0), 0),
