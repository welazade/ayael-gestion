-- Import des cartes clients (gérante). p = {cards: [{card_number, holder_name, bank, note}]}
create or replace function import_cards(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; x jsonb; n_new int := 0; n_upd int := 0; n_same int := 0; num text; nm text; bk text; old cards;
begin
  me := _require('gerante');
  for x in select * from jsonb_array_elements(coalesce(p->'cards', '[]')) loop
    num := regexp_replace(coalesce(x->>'card_number',''), '\s', '', 'g');
    nm := upper(trim(coalesce(x->>'holder_name','')));
    bk := upper(trim(coalesce(x->>'bank','')));
    continue when num = '' or bk = '';
    select * into old from cards where card_number = num and bank = bk;
    if old.id is null then
      insert into cards(card_number, holder_name, bank, gtp_id, note, client_id)
      values (num, nm, bk, _num(x,'gtp_id')::bigint, nullif(x->>'note',''), _client_for(nm));
      n_new := n_new + 1;
    elsif (old.holder_name = '' and nm <> '') or old.client_id is null then
      update cards set holder_name = case when holder_name = '' then nm else holder_name end,
                       client_id = coalesce(client_id, _client_for(case when holder_name = '' then nm else holder_name end))
      where id = old.id;
      n_upd := n_upd + 1;
    else
      n_same := n_same + 1;
    end if;
  end loop;
  perform _log('cards');
  return jsonb_build_object('ok', true, 'new', n_new, 'updated', n_upd, 'existing', n_same);
end $$;

-- Import de la fiche clients (gérante).
-- p = {rows: [{card_number, bank, holder_name, phone, active (true/false/null), note}]}
-- Un client par nom ; ses cartes lui sont rattachées. Le statut actif/inactif vient du fichier.
create or replace function import_clients(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; x jsonb; num text; bk text; nm text; ph text; act boolean; nt text; cid bigint; old cards;
        n_cards_new int := 0; n_cards_upd int := 0; n_clients_before int; n_inactive int := 0;
begin
  me := _require('gerante');
  select count(*) into n_clients_before from clients;
  for x in select * from jsonb_array_elements(coalesce(p->'rows', '[]')) loop
    num := regexp_replace(coalesce(x->>'card_number', ''), '\s', '', 'g');
    bk := upper(trim(coalesce(x->>'bank', '')));
    nm := upper(trim(regexp_replace(coalesce(x->>'holder_name', ''), '\s+', ' ', 'g')));
    ph := nullif(trim(coalesce(x->>'phone', '')), '');
    act := case when x ? 'active' and x->>'active' is not null then (x->>'active')::boolean end;
    nt := nullif(trim(coalesce(x->>'note', '')), '');
    continue when num = '' or bk = '' or nm = '';
    cid := _client_for(nm, ph);
    if ph is not null then update clients set phone = ph where id = cid and coalesce(phone, '') = ''; end if;
    select * into old from cards where card_number = num and bank = bk;
    if old.id is null then
      insert into cards(card_number, holder_name, bank, client_id, phone, note, active)
      values (num, nm, bk, cid, ph, nt, coalesce(act, true));
      n_cards_new := n_cards_new + 1;
    else
      update cards set holder_name = case when holder_name = '' then nm else holder_name end,
        client_id = coalesce(client_id, cid), phone = coalesce(phone, ph), note = coalesce(nt, note),
        active = coalesce(act, active)
      where id = old.id;
      n_cards_upd := n_cards_upd + 1;
    end if;
    if act is false then n_inactive := n_inactive + 1; end if;
  end loop;
  perform _log('cards');
  return jsonb_build_object('ok', true, 'cards_new', n_cards_new, 'cards_updated', n_cards_upd,
    'clients_new', (select count(*) from clients) - n_clients_before, 'inactive', n_inactive);
end $$;

-- Repère les fiches clients probablement en double :
-- même téléphone, ou même nom avec les mots dans un autre ordre.
create or replace function find_duplicates(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; lim int := coalesce(_num(p,'limit')::int, 400);
begin
  me := _require('gerante');
  return (
    with c as (
      select cl.id, cl.name, cl.phone, cl.created_at,
             regexp_replace(coalesce(cl.phone, ''), '\D', '', 'g') as ph,
             (select string_agg(w, ' ' order by w) from unnest(string_to_array(_norm_name(cl.name), ' ')) w where w <> '') as sorted_name
      from clients cl where cl.active),
    k as (
      select 'tel:' || ph as key, id from c where length(ph) >= 8
      union all
      select 'nom:' || sorted_name, id from c where coalesce(sorted_name, '') <> ''),
    g as (select key from k group by key having count(*) > 1 order by key limit lim)
    select coalesce(jsonb_agg(jsonb_build_object('key', g.key, 'clients', (
      select jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'phone', c.phone, 'created_at', c.created_at,
        'cards', (select coalesce(jsonb_agg(jsonb_build_object('card_number', x.card_number, 'bank', x.bank, 'active', x.active)
                    order by x.bank, x.card_number), '[]') from cards x where x.client_id = c.id),
        'n_ops', (select count(*) from operations o where o.client_id = c.id)) order by c.id)
      from k join c on c.id = k.id where k.key = g.key))), '[]')
    from g);
end $$;

-- Fusionne des fiches clients : cartes, opérations et reçus passent sur la fiche gardée.
-- Les fiches fusionnées sont désactivées (rien n'est effacé).
create or replace function merge_clients(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; keep clients; ids bigint[];
begin
  me := _require('gerante');
  select * into keep from clients where id = _num(p,'keep_id')::bigint and active;
  if keep.id is null then raise exception 'Fiche à garder introuvable.'; end if;
  select coalesce(array_agg(v::bigint), '{}') into ids
  from jsonb_array_elements_text(coalesce(p->'merge_ids', '[]')) v where v::bigint <> keep.id;
  if cardinality(ids) = 0 then raise exception 'Choisissez au moins une fiche à fusionner.'; end if;
  update cards set client_id = keep.id where client_id = any(ids);
  update operations set client_id = keep.id where client_id = any(ids);
  update receipts set client_id = keep.id where client_id = any(ids);
  if coalesce(keep.phone, '') = '' then
    update clients set phone = (select phone from clients where id = any(ids) and coalesce(phone, '') <> '' order by id limit 1)
    where id = keep.id;
  end if;
  update clients set active = false,
    note = trim(both ' ' from coalesce(note, '') || ' Fusionnée dans la fiche n° ' || keep.id || ' (' || keep.name || ').')
  where id = any(ids) and active;
  perform _log('clients');
  return jsonb_build_object('ok', true, 'merged', cardinality(ids), 'keep_id', keep.id);
end $$;

