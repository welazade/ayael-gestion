  returning id into oid;
  return oid;
end $$;

-- Nouvelle demande / opération avec un partenaire. Une demande seule ne modifie aucun solde.
create or replace function create_dossier(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; pa partenaires; t text := _txt(p,'type'); d partner_ops; amt numeric := _num(p,'amount');
        ln jsonb; tot numeric := 0; a accounts; ct card_types; lines jsonb := '[]'; cl clients; r jsonb;
begin
  me := _require(null);
  pa := _part(_num(p,'partenaire_id')::bigint);
  if not pa.active then raise exception 'Ce partenaire est désactivé.'; end if;
  if t in ('appro','cartes','virement','ouverture') then
    me := _require_perm('fournisseurs');
  elsif t in ('recharge','paiement','transfert_in','transfert_out') then
    if me.role = 'agent' and not me.can_caisse then raise exception 'Vous n''avez pas le droit de saisir ces opérations.'; end if;
  else
    raise exception 'Type d''opération inconnu.';
  end if;
  if _num(p,'client_id') is not null then
    select * into cl from clients where id = _num(p,'client_id')::bigint;
    if cl.id is null then raise exception 'Client introuvable.'; end if;
  end if;

  if t = 'appro' then
    if jsonb_typeof(p->'lines') is distinct from 'array' or jsonb_array_length(p->'lines') = 0 then
      raise exception 'Indiquez au moins un compte et un montant.';
    end if;
    for ln in select * from jsonb_array_elements(p->'lines') loop
      select * into a from accounts where id = _num(ln,'account_id')::bigint;
      if a.id is null or a.kind not in ('gtp','electronique') then raise exception 'Choisissez un compte UBA / GTCO valide.'; end if;
      if coalesce(_num(ln,'amount'), 0) <= 0 then raise exception 'Montant invalide pour %.', a.name; end if;
      lines := lines || jsonb_build_object('account_id', a.id, 'amount', _num(ln,'amount'));
      tot := tot + _num(ln,'amount');
    end loop;
    amt := tot;
  elsif t = 'cartes' then
    if jsonb_typeof(p->'lines') is distinct from 'array' or jsonb_array_length(p->'lines') = 0 then
      raise exception 'Indiquez au moins un type de cartes.';
    end if;
    for ln in select * from jsonb_array_elements(p->'lines') loop
      select * into ct from card_types where id = _num(ln,'card_type_id')::bigint;
      if ct.id is null then raise exception 'Type de carte introuvable.'; end if;
      if coalesce(_num(ln,'qty'), 0) <= 0 or _num(ln,'qty') <> trunc(_num(ln,'qty')) then raise exception 'Quantité invalide pour %.', ct.name; end if;
      if coalesce(_num(ln,'unit_price'), -1) < 0 then raise exception 'Prix d''achat invalide pour %.', ct.name; end if;
      lines := lines || jsonb_build_object('card_type_id', ct.id, 'qty', _num(ln,'qty')::int, 'unit_price', _num(ln,'unit_price'));
      tot := tot + _num(ln,'qty') * _num(ln,'unit_price');
    end loop;
    amt := tot;
  elsif t = 'ouverture' then
    if amt is null or amt = 0 then raise exception 'Indiquez le solde d''ouverture.'; end if;
    if _txt(p,'details') is null then raise exception 'Indiquez la justification du solde d''ouverture.'; end if;
  else
    if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  end if;
  if t = 'recharge' and (_txt(p,'card_ref') is null or (cl.id is null and _txt(p,'client_name') is null)) then
    raise exception 'Indiquez le client et la référence de sa carte.';
  end if;
  if t in ('paiement','transfert_in','transfert_out') and _txt(p,'beneficiary') is null then
    raise exception 'Indiquez le bénéficiaire.';
  end if;
  -- Recharge à crédit : autorisation et plafond vérifiés dès la commande (la dette ne naît qu'à la réussite).
  if t = 'recharge' and _bool(p,'credit') then
    tot := coalesce(_num(p,'billed'), amt) - coalesce(_num(p,'encaisse'), 0);
    if tot > 0 then
      r := to_jsonb(_credit_check(me, cl, tot, _bool(p,'force_credit')));
      if r is not null and r <> 'null'::jsonb then raise exception 'PLAFOND: %', r #>> '{}'; end if;
    end if;
  end if;

  insert into partner_ops(partenaire_id, parent_id, type, created_by, agence_id, client_id, client_name, donneur, beneficiary, beneficiary_phone,
                          service, card_ref, amount, billed, fees, fees_to, due_partner, to_recover, lines, invoice_ref, invoice_amount,
                          reference, details)
  values (pa.id, _num(p,'parent_id')::bigint, t, me.id, coalesce(me.agence_id, _main()), cl.id,
          case when cl.id is null then upper(_txt(p,'client_name')) end, _txt(p,'donneur'), _txt(p,'beneficiary'), _txt(p,'beneficiary_phone'),
          _txt(p,'service'), regexp_replace(coalesce(_txt(p,'card_ref'), ''), '\s', '', 'g'), amt,
          case when t = 'recharge' then coalesce(_num(p,'billed'), amt) end,
          coalesce(_num(p,'fees'), 0), _txt(p,'fees_to'),
          case when t in ('recharge','transfert_out') then coalesce(_num(p,'due_partner'), amt) end,
          case when t in ('paiement','transfert_in') then coalesce(_num(p,'to_recover'), amt) end,
          lines, _txt(p,'invoice_ref'), _num(p,'invoice_amount'), _txt(p,'reference'), _txt(p,'details'))
  returning * into d;
  if t = 'recharge' and _bool(p,'credit') then
    update partner_ops set credit = true, credit_due = coalesce(_txt(p,'credit_due')::date, current_date + coalesce(cl.credit_days, 30))
    where id = d.id returning * into d;
  end if;
  update partner_ops set ref = case t when 'appro' then 'APP' when 'recharge' then 'RCH' when 'paiement' then 'PAY'
      when 'transfert_in' then 'TRI' when 'transfert_out' then 'TRO' when 'cartes' then 'CRT' when 'virement' then 'VIR' else 'OUV' end
      || '-' || lpad(d.id::text, 6, '0'), card_ref = nullif(card_ref, '')
    where id = d.id returning * into d;
  perform _log('partenaires');

  -- Effets immédiats demandés en même temps (virement, ouverture, encaissement du client, paiement immédiat des cartes).
  if t = 'virement' then
    r := dossier_action(jsonb_build_object('dossier_id', d.id, 'action', 'virement', 'amount', amt, 'from_id', p->'from_id',
                                           'idem_key', p->'idem_key', 'reference', p->'reference'));
  elsif t = 'ouverture' then
    r := dossier_action(jsonb_build_object('dossier_id', d.id, 'action', 'ouverture', 'idem_key', p->'idem_key', 'scope', p->'scope'));
  elsif t in ('recharge','transfert_out') and coalesce(_num(p,'encaisse'), 0) > 0 then
    r := dossier_action(jsonb_build_object('dossier_id', d.id, 'action', 'encaissement', 'amount', p->'encaisse',
                                           'account_id', p->'account_id', 'idem_key', p->'idem_key'));
  elsif t = 'cartes' and coalesce(_num(p,'paid_now'), 0) > 0 then
    r := dossier_action(jsonb_build_object('dossier_id', d.id, 'action', 'paiement_cartes', 'amount', p->'paid_now',
                                           'from_id', p->'from_id', 'idem_key', p->'idem_key'));
  end if;
  select * into d from partner_ops where id = d.id;
  return jsonb_build_object('ok', true, 'dossier', _pop_row(d, _can(me, 'fournisseurs')));
end $$;

-- Confirmation d'une étape d'un dossier. Chaque effet financier est enregistré une seule fois.
-- actions : encaissement, execution, echec, rembourser, paiement, recu_partenaire, alimentation, virement,
--           reception, paiement_cartes, facture, en_cours, cloturer, annuler, ouverture, reference
create or replace function dossier_action(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; d partner_ops; pa partenaires; act text := _txt(p,'action'); idem text := _txt(p,'idem_key');
        amt numeric := _num(p,'amount'); a accounts; oid bigint; canp boolean; done numeric; rest numeric; ln jsonb; ol jsonb;
        q int; recv int; ct card_types; tot numeric := 0; acc_cards bigint; v numeric; o operations; cl clients;
begin
  me := _require(null);
  canp := _can(me, 'fournisseurs');
  if idem is not null and exists (select 1 from operations where idem_key = idem) then
    select * into d from partner_ops where id = (select partner_op_id from operations where idem_key = idem limit 1);
    return jsonb_build_object('ok', true, 'duplicate', true, 'dossier', _pop_row(d, canp), 'position', (select _bal(account_id) from partenaires where id = d.partenaire_id));
  end if;
  select * into d from partner_ops where id = _num(p,'dossier_id')::bigint for update;
  if d.id is null then raise exception 'Dossier introuvable.'; end if;
  pa := _part(d.partenaire_id);
  if d.status = 'annulee' then raise exception 'Ce dossier est annulé.'; end if;
  if act not in ('encaissement','paiement','reference','rembourser') and not canp then
    raise exception 'Seule une personne autorisée (droit « fournisseurs et partenaires ») peut confirmer cette étape.';
  end if;
  if not canp and me.role <> 'gerante' and d.agence_id is distinct from me.agence_id then
    raise exception 'Ce dossier appartient à une autre agence.';
  end if;

  if act = 'encaissement' then
    -- Le client nous paie (recharge par le partenaire) ou nous recevons les fonds (transfert dans le 2e sens).
    if d.type not in ('recharge','transfert_out') then raise exception 'Encaissement impossible pour ce type d''opération.'; end if;
    if d.status in ('echouee','rembourse') then raise exception 'Opération échouée ou remboursée.'; end if;
    if d.status in ('reussie','termine') then raise exception 'Opération déjà réalisée : enregistrez plutôt un règlement du client.'; end if;
    a := _check_use(me, coalesce(_num(p,'account_id')::bigint, _caisse_of(me.id)));
    done := (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'encaissement');
    rest := case when d.type = 'recharge' then coalesce(d.billed, d.amount) else d.amount end - done;
    amt := coalesce(amt, rest);
    if amt <= 0 then raise exception 'Montant invalide.'; end if;
    if amt > rest then raise exception 'Le montant dépasse ce qui reste à encaisser (% F).', rest; end if;
    oid := _pop_insert(d, me, 'partenaire', 'encaissement', a.id, null, amt, 0, idem,
                       d.ref || ' · encaissement ' || coalesce((select name from clients where id = d.client_id), d.client_name, d.donneur, ''));
    insert into movements(operation_id, account_id, amount) values (oid, a.id, amt);
    if d.type = 'transfert_out' and d.status = 'en_attente' then update partner_ops set status = 'en_cours' where id = d.id; end if;

  elsif act = 'execution' then
    -- Le partenaire a réalisé l'opération : la recharge a réussi / le bénéficiaire a été payé.
    if d.type not in ('recharge','transfert_out') then raise exception 'Action impossible pour ce type d''opération.'; end if;
    if d.status in ('reussie','termine','echouee','rembourse') then raise exception 'Cette opération est déjà clôturée.'; end if;
    amt := coalesce(amt, d.due_partner, d.amount);
    if amt < 0 then raise exception 'Montant invalide.'; end if;
    done := (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'encaissement');
    oid := _pop_insert(d, me, 'partenaire', 'execution', pa.account_id, null, amt,
                       case when d.type = 'recharge' then coalesce(d.billed, d.amount) - amt else d.amount - amt end, idem,
                       d.ref || case when d.type = 'recharge' then ' · recharge réussie ' || coalesce(d.service, '') || ' ' || coalesce(_mask(d.card_ref), '')
                                     else ' · payé par le partenaire à ' || coalesce(d.beneficiary, '') end, pa.account_id);
    insert into movements(operation_id, account_id, amount) values (oid, pa.account_id, -amt);
    -- Recharge réussie non payée en totalité : la créance du client naît maintenant (indépendante du compte partenaire).
    if d.type = 'recharge' then
      v := coalesce(d.billed, d.amount) - done;
      if v > 0 then
        select * into cl from clients where id = d.client_id;
        if cl.id is null then
          raise exception 'Le client n''a pas tout payé (reste % F) et n''a pas de fiche client : encaissez le reste avant de confirmer.', v;
        end if;
        perform _credit_create(me, cl, v, coalesce(d.credit_due, current_date + cl.credit_days), null, null, d.id,
                               d.ref || ' · recharge ' || coalesce(d.service, ''), d.ref);
      end if;
    end if;
    update partner_ops set status = case when d.type = 'recharge' then 'reussie' else 'termine' end, due_partner = amt,
      reference = coalesce(_txt(p,'reference'), reference) where id = d.id;

  elsif act = 'echec' then
    if d.status in ('reussie','termine') then raise exception 'Opération déjà réalisée : annulez-la si besoin.'; end if;
    update partner_ops set status = 'echouee', cancel_reason = coalesce(_txt(p,'reason'), cancel_reason) where id = d.id;

  elsif act = 'rembourser' then
    -- On rend au client ce qu'il avait payé pour une opération non réalisée.
    if d.status in ('reussie','termine') then raise exception 'Opération réalisée : remboursement impossible.'; end if;
    a := _check_use(me, coalesce(_num(p,'account_id')::bigint, _caisse_of(me.id)));
    done := (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'encaissement')
          - (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'remboursement');
    amt := coalesce(amt, done);
    if amt <= 0 or amt > done then raise exception 'Rien à rembourser (encaissé : % F).', done; end if;
    perform _check_funds(a, amt);
    oid := _pop_insert(d, me, 'partenaire', 'remboursement', a.id, null, amt, 0, idem, d.ref || ' · remboursement du client');
    insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt);
    update partner_ops set status = 'rembourse' where id = d.id;

  elsif act = 'paiement' then
    -- Nous payons le bénéficiaire avec notre caisse : sortie de caisse + somme à récupérer auprès du partenaire.
    if d.type not in ('paiement','transfert_in') then raise exception 'Action impossible pour ce type d''opération.'; end if;
    if d.status in ('termine','echouee','rembourse') then raise exception 'Cette opération est déjà clôturée.'; end if;
    a := _check_use(me, coalesce(_num(p,'account_id')::bigint, _caisse_of(me.id)));
    amt := coalesce(amt, d.amount);
    if amt <= 0 then raise exception 'Montant invalide.'; end if;
    v := coalesce(_num(p,'to_recover'), d.to_recover, amt);
    perform _check_funds(a, amt);
    oid := _pop_insert(d, me, 'partenaire', 'paiement', a.id, pa.account_id, amt, v - amt, idem,
                       d.ref || ' · payé à ' || coalesce(d.beneficiary, ''), pa.account_id);
    insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt), (oid, pa.account_id, v);
    update partner_ops set status = 'termine', to_recover = v, reference = coalesce(_txt(p,'reference'), reference) where id = d.id;

  elsif act = 'recu_partenaire' then
    -- Le partenaire confirme avoir reçu les fonds (aucun effet sur les soldes).
    update partner_ops set info = info || jsonb_build_object('recu_partenaire', jsonb_build_object('at', now(), 'by', me.full_name,
           'amount', coalesce(amt, d.amount), 'reference', _txt(p,'reference'))),
           status = case when status = 'en_attente' then 'en_cours' else status end where id = d.id;

  elsif act = 'alimentation' then
    if d.type <> 'appro' then raise exception 'Action impossible pour ce type d''opération.'; end if;
    select * into a from accounts where id = _num(p,'account_id')::bigint;
    if a.id is null or a.kind not in ('gtp','electronique') then raise exception 'Choisissez le compte alimenté.'; end if;
    if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
    oid := _pop_insert(d, me, 'approvisionnement', 'alimentation', a.id, pa.account_id, amt, 0, idem,
                       d.ref || ' · alimentation ' || a.name || coalesce(' · réf. ' || _txt(p,'reference'), ''), pa.account_id);
    insert into movements(operation_id, account_id, amount) values (oid, a.id, amt), (oid, pa.account_id, -amt);
    done := (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'alimentation');
    update partner_ops set status = case when done >= d.amount then 'termine' else 'partiel' end where id = d.id;

  elsif act in ('virement','paiement_cartes') then
    -- Argent envoyé au partenaire : sort de notre caisse / banque et augmente notre avance chez lui.
    if act = 'paiement_cartes' and d.type <> 'cartes' then raise exception 'Action impossible pour ce type d''opération.'; end if;
    select * into a from accounts where id = _num(p,'from_id')::bigint;
    if a.id is null or a.kind in ('fournisseur','gtp','avoir') then raise exception 'Choisissez d''où sort l''argent.'; end if;
    if not _mine(me, a) then raise exception 'L''argent doit venir d''un compte de votre agence.'; end if;
    if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
    perform _check_funds(a, amt);
    acc_cards := case when act = 'paiement_cartes' then _part_cards(pa) else pa.account_id end;
    oid := _pop_insert(d, me, 'transfert', act, a.id, acc_cards, amt, 0, idem,
                       d.ref || case when act = 'virement' then ' · virement à ' else ' · paiement cartes à ' end || pa.name
                       || coalesce(' · réf. ' || _txt(p,'reference'), ''), acc_cards);
    insert into movements(operation_id, account_id, amount) values (oid, a.id, -amt), (oid, acc_cards, amt);
    if d.type = 'virement' then update partner_ops set status = 'termine' where id = d.id; end if;

  elsif act = 'reception' then
    -- Cartes reçues : entrent en stock et créent la dette d'achat.
    if d.type <> 'cartes' then raise exception 'Action impossible pour ce type d''opération.'; end if;
    acc_cards := _part_cards(pa);
    oid := _pop_insert(d, me, 'partenaire', 'reception', acc_cards, null, 0, 0, idem, d.ref || ' · réception de cartes', acc_cards);
    for ln in select * from jsonb_array_elements(coalesce(p->'lines', '[]')) loop
      q := coalesce(_num(ln,'qty'), 0)::int;
      continue when q <= 0;
      select l into ol from jsonb_array_elements(d.lines) l where (l->>'card_type_id')::bigint = _num(ln,'card_type_id')::bigint;
      if ol is null then raise exception 'Ce type de carte ne figure pas dans la commande.'; end if;
      recv := (select coalesce(sum(s.qty), 0) from stock_moves s join operations o2 on o2.id = s.operation_id
               where s.partner_op_id = d.id and o2.status = 'ok' and s.kind = 'reception' and s.card_type_id = (ol->>'card_type_id')::bigint);
      if q > (ol->>'qty')::int - recv then
        raise exception 'Quantité reçue supérieure à la quantité restant à recevoir (% restante(s)).', (ol->>'qty')::int - recv;
      end if;
      insert into stock_moves(user_id, agence_id, card_type_id, qty, kind, unit_cost, partner_op_id, operation_id)
        values (me.id, coalesce(me.agence_id, _main()), (ol->>'card_type_id')::bigint, q, 'reception', (ol->>'unit_price')::numeric, d.id, oid);
      tot := tot + q * (ol->>'unit_price')::numeric;
    end loop;
    if not exists (select 1 from stock_moves where operation_id = oid) then raise exception 'Indiquez les quantités reçues.'; end if;
    update operations set amount = tot where id = oid;
    if tot > 0 then insert into movements(operation_id, account_id, amount) values (oid, acc_cards, -tot); end if;
    update partner_ops set status = case when not exists (
        select 1 from jsonb_array_elements(d.lines) l
        where (l->>'qty')::int > (select coalesce(sum(s.qty), 0) from stock_moves s join operations o2 on o2.id = s.operation_id
                                  where s.partner_op_id = d.id and o2.status = 'ok' and s.kind = 'reception'
                                    and s.card_type_id = (l->>'card_type_id')::bigint)) then 'termine' else 'partiel' end
      where id = d.id;

  elsif act = 'facture' then
    update partner_ops set invoice_ref = coalesce(_txt(p,'invoice_ref'), invoice_ref), invoice_amount = coalesce(_num(p,'invoice_amount'), invoice_amount)
      where id = d.id;

  elsif act = 'en_cours' then
    if d.status = 'en_attente' then update partner_ops set status = 'en_cours' where id = d.id; end if;

  elsif act = 'cloturer' then
    if d.type not in ('appro','cartes') then raise exception 'Action impossible pour ce type d''opération.'; end if;
    update partner_ops set status = 'termine', details = coalesce(details || ' · ', '') || 'Clôturé : ' || coalesce(_txt(p,'reason'), 'reste annulé')
      where id = d.id;

  elsif act = 'ouverture' then
    if d.type <> 'ouverture' then raise exception 'Action impossible.'; end if;
    acc_cards := case when _txt(p,'scope') = 'cartes' then _part_cards(pa) else pa.account_id end;
    oid := _pop_insert(d, me, 'ajustement', 'ouverture', acc_cards, null, d.amount, 0, idem,
                       d.ref || ' · solde d''ouverture · ' || coalesce(d.details, ''), acc_cards);
    insert into movements(operation_id, account_id, amount) values (oid, acc_cards, d.amount);
    update partner_ops set status = 'termine' where id = d.id;

  elsif act = 'annuler' then
    -- Contre-écriture de tous les effets confirmés du dossier ; l'historique est conservé.
    if _txt(p,'reason') is null then raise exception 'Indiquez le motif de l''annulation.'; end if;
    for o in select * from operations where partner_op_id = d.id and status = 'ok' loop
      update operations set status = 'annulee', cancelled_at = now(), cancelled_by = me.id, cancel_reason = _txt(p,'reason') where id = o.id;
      insert into movements(operation_id, account_id, amount, reversal)
        select o.id, account_id, -amount, true from movements where operation_id = o.id and not reversal;
    end loop;
    update partner_ops set status = 'annulee', cancel_reason = _txt(p,'reason') where id = d.id;

  elsif act = 'reference' then
    update partner_ops set reference = coalesce(_txt(p,'reference'), reference), details = coalesce(_txt(p,'details'), details) where id = d.id;

  else
    raise exception 'Action inconnue.';
  end if;

  update partner_ops set updated_at = now() where id = d.id;
  perform _log('operations');
  select * into d from partner_ops where id = d.id;
  return jsonb_build_object('ok', true, 'dossier', _pop_row(d, canp), 'position', _bal(pa.account_id),
    'cards_position', case when pa.cards_account_id is not null and not pa.cartes_compensees then _bal(pa.cards_account_id) end);
end $$;

create or replace function get_dossier(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; d partner_ops; canp boolean;
begin
  me := _require(null);
  canp := _can(me, 'fournisseurs');
  select * into d from partner_ops where id = _num(p,'id')::bigint;
  if d.id is null then raise exception 'Dossier introuvable.'; end if;
  if not canp and (d.type not in ('recharge','paiement','transfert_in','transfert_out') or (me.role <> 'gerante' and d.agence_id is distinct from me.agence_id)) then
    raise exception 'Accès refusé.';
  end if;
  return _pop_row(d, canp);
end $$;

-- Relevé : solde initial, mouvements confirmés, solde final (périmètre : financier ou cartes).
create or replace function releve_partenaire(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; pa partenaires; acc bigint; d1 date := coalesce(_txt(p,'from')::date, date '2000-01-01'); d2 date := coalesce(_txt(p,'to')::date, current_date);
        ouv numeric;
begin
  me := _require_perm('fournisseurs');
  pa := _part(_num(p,'id')::bigint);
  acc := case when _txt(p,'scope') = 'cartes' then _part_cards(pa) else pa.account_id end;
  ouv := (select coalesce(sum(m.amount), 0) from movements m join operations o on o.id = m.operation_id
          where m.account_id = acc and o.created_at < d1::timestamptz);
  return jsonb_build_object(
    'partenaire', pa.name, 'scope', coalesce(_txt(p,'scope'), 'financier'), 'from', d1, 'to', d2, 'opening', ouv,
    'closing', ouv + (select coalesce(sum(m.amount), 0) from movements m join operations o on o.id = m.operation_id
                      where m.account_id = acc and o.created_at >= d1::timestamptz and o.created_at < (d2 + 1)::timestamptz),
    'lines', (select coalesce(jsonb_agg(x order by x.at, x.mid), '[]') from (
      select m.id as mid, o.created_at as at, m.amount as variation, m.reversal, o.id as op_id, o.kind, o.stage, o.status, o.details,
             (select ref from partner_ops where id = o.partner_op_id) as ref,
             (select type from partner_ops where id = o.partner_op_id) as type,
             (select full_name from profiles where id = o.user_id) as agent
      from movements m join operations o on o.id = m.operation_id
      where m.account_id = acc and o.created_at >= d1::timestamptz and o.created_at < (d2 + 1)::timestamptz) x));
end $$;

-- Stock de cartes physiques
create or replace function save_card_type(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cid bigint := _num(p,'id')::bigint; r card_types;
begin
  me := _require_perm('fournisseurs');
  if _txt(p,'name') is null then raise exception 'Le nom du type de carte est obligatoire.'; end if;
  if cid is null then
    insert into card_types(name, bank, sale_price) values (_txt(p,'name'), upper(_txt(p,'bank')), coalesce(_num(p,'sale_price'), 0)) returning * into r;
    -- Produit de vente associé (diminue le stock à chaque vente).
    insert into products(name, direction, category, card_type_id, sort) values ('Vente ' || r.name, 'entree', 'Cartes', r.id, 51);
  else
    update card_types set name = _txt(p,'name'), bank = upper(_txt(p,'bank')), sale_price = coalesce(_num(p,'sale_price'), sale_price),
      active = coalesce((p->>'active')::boolean, active) where id = cid returning * into r;
    if r.id is null then raise exception 'Type de carte introuvable.'; end if;
    update products set active = r.active where card_type_id = r.id and not r.active;
  end if;
  perform _log('products');
  return to_jsonb(r);
end $$;

create or replace function list_stock(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles;
begin
  me := _require(null);
  return (select coalesce(jsonb_agg(jsonb_build_object(
      'id', t.id, 'name', t.name, 'bank', t.bank, 'sale_price', t.sale_price, 'active', t.active,
      'stock', (select coalesce(sum(s.qty), 0) from stock_moves s left join operations o on o.id = s.operation_id
                where s.card_type_id = t.id and (o.id is null or o.status = 'ok')),
      'to_receive', (select coalesce(sum((l->>'qty')::int), 0) from partner_ops d, jsonb_array_elements(d.lines) l
                     where d.type = 'cartes' and d.status in ('en_attente','partiel') and (l->>'card_type_id')::bigint = t.id)
                  - (select coalesce(sum(s.qty), 0) from stock_moves s join operations o on o.id = s.operation_id
                     join partner_ops d on d.id = s.partner_op_id
                     where s.card_type_id = t.id and s.kind = 'reception' and o.status = 'ok' and d.status in ('en_attente','partiel')),
      'sold_month', (select coalesce(-sum(s.qty), 0) from stock_moves s join operations o on o.id = s.operation_id
                     where s.card_type_id = t.id and s.kind = 'vente' and o.status = 'ok' and s.created_at >= date_trunc('month', now())),
      'last_cost', (select unit_cost from stock_moves s where s.card_type_id = t.id and s.kind = 'reception' order by s.id desc limit 1)
    ) order by t.active desc, t.sort, t.name), '[]') from card_types t);
end $$;

