-- Règlement d'un client : augmente la caisse / le compte, réduit sa dette. Le surplus devient une avance.
-- p = { client_id, amount, account_id, reference, date, allocations: [{credit_id, amount}] }
create or replace function op_reglement(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cl clients; a accounts; av bigint; amt numeric := _num(p,'amount'); oid bigint; ln jsonb; tot numeric := 0;
        st jsonb; c jsonb; dt date := coalesce(_txt(p,'date')::date, current_date);
begin
  me := _require(null);
  select * into cl from clients where id = _num(p,'client_id')::bigint;
  if cl.id is null then raise exception 'Client introuvable.'; end if;
  if amt is null or amt <= 0 then raise exception 'Montant invalide.'; end if;
  if dt > current_date then raise exception 'La date du règlement ne peut pas être dans le futur.'; end if;
  a := _check_use(me, coalesce(_num(p,'account_id')::bigint, _caisse_of(me.id)));
  select id into av from accounts where kind = 'avoir' order by id limit 1;
  insert into operations(user_id, kind, op_day, account_id, account2_id, amount, details, category, client_id)
  values (me.id, 'avoir', dt, a.id, av, amt, 'Règlement de ' || cl.name || coalesce(' · réf. ' || _txt(p,'reference'), ''), 'reglement', cl.id)
  returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, amt), (oid, av, -amt);
  -- Affectation choisie (responsables) ; sans choix : aux dettes les plus anciennes, automatiquement.
  if jsonb_typeof(p->'allocations') = 'array' and jsonb_array_length(p->'allocations') > 0 then
    if me.role = 'agent' then raise exception 'Seul un responsable peut choisir les ventes réglées.'; end if;
    st := _client_credit_state(cl.id);
    for ln in select * from jsonb_array_elements(p->'allocations') loop
      continue when coalesce(_num(ln,'amount'), 0) <= 0;
      select x into c from jsonb_array_elements(st) x where (x->>'id')::bigint = _num(ln,'credit_id')::bigint;
      if c is null then raise exception 'Vente à crédit introuvable pour ce client.'; end if;
      tot := tot + _num(ln,'amount');
      if tot > amt then raise exception 'Les montants affectés dépassent le règlement.'; end if;
      insert into credit_allocs(credit_id, operation_id, amount) values ((c->>'id')::bigint, oid, _num(ln,'amount'));
    end loop;
  end if;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'position', _client_pos(cl.id));
end $$;

-- Correction justifiée du solde d'un client (dette oubliée, erreur…).
create or replace function op_client_ajust(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cl clients; av bigint; amt numeric := _num(p,'amount'); oid bigint;
begin
  me := _require_perm('ajust');
  select * into cl from clients where id = _num(p,'client_id')::bigint;
  if cl.id is null then raise exception 'Client introuvable.'; end if;
  if amt is null or amt = 0 then raise exception 'Indiquez le montant (+ : il nous doit plus ; − : il nous doit moins).'; end if;
  if _txt(p,'reason') is null then raise exception 'Indiquez le motif de la correction.'; end if;
  select id into av from accounts where kind = 'avoir' order by id limit 1;
  insert into operations(user_id, kind, account_id, amount, details, category, client_id)
  values (me.id, 'ajustement', av, amt, 'Correction compte client ' || cl.name || ' · ' || _txt(p,'reason'), 'client', cl.id) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, av, amt);
  -- Une dette ajoutée par correction est suivie comme une vente à crédit (échéance immédiate).
  if amt > 0 then
    insert into client_credits(user_id, client_id, operation_id, amount, due_date, label)
    values (me.id, cl.id, oid, amt, current_date, 'Correction : ' || _txt(p,'reason'));
  end if;
  perform _log('operations');
  return jsonb_build_object('ok', true, 'position', _client_pos(cl.id));
end $$;

-- Compte d'un client : position, réglages, ventes à crédit, mouvements récents.
create or replace function client_account(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; cl clients; pos numeric;
begin
  me := _require(null);
  select * into cl from clients where id = _num(p,'client_id')::bigint;
  if cl.id is null then raise exception 'Client introuvable.'; end if;
  pos := _client_pos(cl.id);
  return jsonb_build_object('client_id', cl.id, 'name', cl.name, 'position', pos, 'dette', greatest(pos, 0), 'avance', greatest(-pos, 0),
    'credit_allowed', cl.credit_allowed, 'credit_limit', cl.credit_limit, 'credit_days', cl.credit_days,
    'disponible', case when cl.credit_allowed then greatest(cl.credit_limit - greatest(pos, 0), 0) else 0 end,
    'credits', _client_credit_state(cl.id),
    'mouvements', (select coalesce(jsonb_agg(x order by x.created_at desc), '[]') from (
        select o.id, o.created_at, o.op_day, o.category, o.kind, o.status, o.details, m.amount as variation,
               (select full_name from profiles where id = o.user_id) as agent, (select name from accounts where id = o.account_id) as account
        from movements m join operations o on o.id = m.operation_id join accounts a on a.id = m.account_id
        where a.kind = 'avoir' and o.client_id = cl.id and not m.reversal
        order by o.created_at desc limit 80) x));
end $$;

-- Tableau des créances clients (filtre : recherche, seulement échus).
create or replace function credit_overview(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; q text := upper(coalesce(_txt(p,'q'), '')); res jsonb := '[]'; r record; st jsonb; echu numeric; late int; nxt date;
        t_du numeric := 0; t_echu numeric := 0; t_av numeric := 0;
begin
  me := _require(null);
  for r in
    select cl.id, cl.name, cl.phone, cl.credit_limit, cl.credit_allowed, _client_pos(cl.id) as pos
    from clients cl
    where (exists (select 1 from client_credits c where c.client_id = cl.id) or cl.credit_allowed
           or exists (select 1 from operations o where o.client_id = cl.id and o.kind = 'avoir'))
      and (q = '' or upper(cl.name) like '%' || q || '%' or replace(coalesce(cl.phone, ''), ' ', '') like '%' || replace(q, ' ', '') || '%')
  loop
    continue when r.pos = 0 and not r.credit_allowed;
    st := _client_credit_state(r.id);
    select coalesce(sum((x->>'remaining')::numeric) filter (where (x->>'days_late')::int > 0), 0),
           coalesce(max((x->>'days_late')::int), 0),
           min((x->>'due_date')::date) filter (where (x->>'remaining')::numeric > 0)
      into echu, late, nxt from jsonb_array_elements(st) x;
    if r.pos > 0 then t_du := t_du + r.pos; t_echu := t_echu + least(echu, r.pos); else t_av := t_av - r.pos; end if;
    continue when coalesce(_bool(p,'echus'), false) and echu <= 0;
    res := res || jsonb_build_object('client_id', r.id, 'name', r.name, 'phone', r.phone, 'dette', greatest(r.pos, 0), 'avance', greatest(-r.pos, 0),
      'echu', least(echu, greatest(r.pos, 0)), 'days_late', late, 'next_due', nxt, 'credit_limit', r.credit_limit, 'credit_allowed', r.credit_allowed,
      'open_n', (select count(*) from jsonb_array_elements(st) x where (x->>'remaining')::numeric > 0));
  end loop;
  return jsonb_build_object('total_du', t_du, 'total_echu', t_echu, 'total_non_echu', t_du - t_echu, 'total_avances', t_av,
    'clients', (select coalesce(jsonb_agg(x order by (x->>'days_late')::int desc, (x->>'dette')::numeric desc), '[]') from jsonb_array_elements(res) x));
end $$;

