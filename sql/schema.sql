  insert into operations(user_id, kind, account_id, amount, details)
  values (me.id, 'ajustement', a.id, amt, motif) returning id into oid;
  insert into movements(operation_id, account_id, amount) values (oid, a.id, amt);
  perform _log('operations');
  return jsonb_build_object('ok', true, 'id', oid, 'balance', _bal(a.id));
end $$;

-- Annulation tracée : l'opération reste visible, barrée, avec des mouvements inverses.
-- Un agent peut annuler sa propre opération dans les 30 minutes (hors clôture) ; sinon la gérante.
create or replace function op_annuler(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; o operations; motif text := _txt(p,'reason');
begin
  me := _require(null);
  select * into o from operations where id = _num(p,'id')::bigint for update;
  if o.id is null then raise exception 'Opération introuvable.'; end if;
  if o.status <> 'ok' then raise exception 'Cette opération est déjà annulée.'; end if;
  if motif is null then raise exception 'Indiquez le motif de l''annulation.'; end if;
  if me.role <> 'gerante' then
    if o.user_id is distinct from me.id or o.created_at < now() - interval '30 minutes' or o.closing_id is not null
       or o.kind not in ('caisse','recharge','depense') then
      raise exception 'Seule la gérante peut annuler cette opération (délai de 30 minutes dépassé ou caisse clôturée).';
    end if;
  end if;
  update operations set status = 'annulee', cancelled_at = now(), cancelled_by = me.id, cancel_reason = motif where id = o.id;
  insert into movements(operation_id, account_id, amount, reversal)
    select o.id, account_id, -amount, true from movements where operation_id = o.id and not reversal;
  perform _log('operations');
  return jsonb_build_object('ok', true);
end $$;

create or replace function list_operations(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; d1 date := coalesce(_txt(p,'from')::date, current_date); d2 date := coalesce(_txt(p,'to')::date, current_date);
        uid uuid := _txt(p,'user_id')::uuid; k text := _txt(p,'kind'); acc bigint := _num(p,'account_id')::bigint;
        q text := _txt(p,'q'); lim int := least(coalesce(_num(p,'limit')::int, 300), 20000);
begin
  me := _require(null);
  if me.role <> 'gerante' then uid := me.id; end if;
  return (
    select coalesce(jsonb_agg(_op_row(o) order by o.created_at desc, o.id desc), '[]') from (
      select * from operations o
      where o.op_day between d1 and d2
        and (uid is null or o.user_id = uid)
        and (k is null or o.kind = k)
        and (acc is null or o.account_id = acc or o.account2_id = acc)
        and (_num(p,'client_id') is null or o.client_id = _num(p,'client_id')::bigint)
        and (_num(p,'receipt_id') is null or o.receipt_id = _num(p,'receipt_id')::bigint)
        and (_bool(p,'include_cancelled') or o.status = 'ok' or _txt(p,'include_cancelled') is null)
        and (q is null or o.details ilike '%'||q||'%'
             or exists (select 1 from cards c where c.id = o.card_id and (c.card_number like q||'%' or c.holder_name ilike '%'||q||'%')))
      order by o.created_at desc, o.id desc limit lim) o);
end $$;

