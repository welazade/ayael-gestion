-- =====================================================================
--  AYAEL ENTREPRISE — Registre de back-office
--  Schéma de la base de données (Supabase / PostgreSQL)
--
--  À coller en entier dans Supabase > SQL Editor > New query > Run.
--  Le script peut être relancé sans danger (il ne supprime aucune donnée).
--
--  Principe : chaque opération crée des « mouvements » (+ / −) sur des
--  comptes (GTP, comptes électroniques, caisses des agents, coffre).
--  Le solde d'un compte = somme de ses mouvements. Rien n'est effacé :
--  une annulation ajoute des mouvements inverses.
-- =====================================================================

