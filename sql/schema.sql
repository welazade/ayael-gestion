-- Import des cartes clients (gérante). p = {cards: [{card_number, holder_name, bank, note}]}
create or replace function import_cards(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; x jsonb; n_new int := 0; n_upd int := 0; n_same int := 0; num text; nm text; bk text; old cards;
begin
  me := _require('gerante');
  for x in select * from jsonb_array_elements(coalesce(p->'cards', '[]')) loop
    num := regexp_replace(coalesce(x->>'card_number',''), '\s', '', 'g');
    nm := upper(trim(coalesce(x->>'holder_name','')));
    bk := upper(trim(coalesce(x->>'bank','')));
    continue when num = '' or bk = '';
    select * into old from cards where card_number = num and bank = bk;
    if old.id is null then
      insert into cards(card_number, holder_name, bank, gtp_id, note, client_id)
      values (num, nm, bk, _num(x,'gtp_id')::bigint, nullif(x->>'note',''), _client_for(nm));
      n_new := n_new + 1;
    elsif (old.holder_name = '' and nm <> '') or old.client_id is null then
      update cards set holder_name = case when holder_name = '' then nm else holder_name end,
                       client_id = coalesce(client_id, _client_for(case when holder_name = '' then nm else holder_name end))
      where id = old.id;
      n_upd := n_upd + 1;
    else
      n_same := n_same + 1;
    end if;
  end loop;
  perform _log('cards');
  return jsonb_build_object('ok', true, 'new', n_new, 'updated', n_upd, 'existing', n_same);
end $$;

