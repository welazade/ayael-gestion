-- ---------- Partenaires et fournisseurs : fonctions ---------------------------

create or replace function _part(pid bigint) returns partenaires
language plpgsql stable security definer set search_path = public as $$
declare r partenaires;
begin
  select * into r from partenaires where id = pid;
  if r.id is null then raise exception 'Partenaire introuvable.'; end if;
  return r;
end $$;

-- Compte qui porte les dettes « cartes » : le même compte si elles se compensent, sinon un compte séparé.
create or replace function _part_cards(pa partenaires) returns bigint
language sql stable as $$
  select case when pa.cartes_compensees or pa.cards_account_id is null then pa.account_id else pa.cards_account_id end
$$;

create or replace function _mask(s text) returns text
language sql immutable as $$
  select case when s is null or s = '' then null
              when length(regexp_replace(s, '\s', '', 'g')) <= 4 then '••••'
              else '•••• ' || right(regexp_replace(s, '\s', '', 'g'), 4) end
$$;

create or replace function _pop_label(t text) returns text
language sql immutable as $$
  select case t when 'appro' then 'Approvisionnement UBA / GTCO' when 'recharge' then 'Recharge de carte par le partenaire'
    when 'paiement' then 'Paiement d''un bénéficiaire pour le partenaire' when 'transfert_in' then 'Transfert : le partenaire reçoit, nous payons'
    when 'transfert_out' then 'Transfert : nous recevons, le partenaire paie' when 'cartes' then 'Commande de cartes'
    when 'virement' then 'Virement au partenaire' when 'ouverture' then 'Solde d''ouverture' else t end
$$;

-- Un dossier avec ses montants déjà exécutés (calculés à partir des opérations confirmées).
create or replace function _pop_row(d partner_ops, full_ref boolean default false) returns jsonb
language sql stable security definer set search_path = public as $$
  select (to_jsonb(d) - 'card_ref') || jsonb_build_object(
    'card_ref', case when full_ref then d.card_ref else _mask(d.card_ref) end,
    'card_ref_masked', _mask(d.card_ref),
    'label', _pop_label(d.type),
    'partenaire', (select name from partenaires where id = d.partenaire_id),
    'client', coalesce((select name from clients where id = d.client_id), d.client_name),
    'created_by_name', (select full_name from profiles where id = d.created_by),
    'agence', (select name from agences where id = d.agence_id),
    'encaisse',  (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'encaissement'),
    'rembourse', (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'remboursement'),
    'alimente',  (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'alimentation'),
    'vire',      (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage in ('virement','paiement_cartes')),
    'paye',      (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'paiement'),
    'execute',   (select coalesce(sum(amount), 0) from operations where partner_op_id = d.id and status = 'ok' and stage = 'execution'),
    'recu_cartes', (select coalesce(-sum(m.amount), 0) from operations o join movements m on m.operation_id = o.id and not m.reversal
                    where o.partner_op_id = d.id and o.status = 'ok' and o.stage = 'reception'),
    'received', (select coalesce(jsonb_object_agg(x.card_type_id, x.q), '{}') from (
                   select s.card_type_id, sum(s.qty) as q from stock_moves s join operations o on o.id = s.operation_id
                   where s.partner_op_id = d.id and o.status = 'ok' and s.kind = 'reception' group by s.card_type_id) x),
    'alim_by_acc', (select coalesce(jsonb_object_agg(x.account_id, x.s), '{}') from (
                   select account_id, sum(amount) as s from operations where partner_op_id = d.id and status = 'ok' and stage = 'alimentation'
                   group by account_id) x),
    'pieces', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'mime', mime, 'created_at', created_at) order by id), '[]')
               from pieces where partner_op_id = d.id),
    'ops', (select coalesce(jsonb_agg(jsonb_build_object('id', o.id, 'stage', o.stage, 'amount', o.amount, 'status', o.status,
              'created_at', o.created_at, 'agent', (select full_name from profiles where id = o.user_id),
              'account', (select name from accounts where id = o.account_id), 'details', o.details) order by o.id), '[]')
            from operations o where o.partner_op_id = d.id)
  )
$$;

-- Crée ou modifie la fiche d'un partenaire / fournisseur.
create or replace function save_partenaire(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; pid bigint := _num(p,'id')::bigint; r partenaires; acc bigint; nm text := _txt(p,'name');
begin
  me := _require_perm('fournisseurs');
  if nm is null then raise exception 'Le nom est obligatoire.'; end if;
  if exists (select 1 from partenaires where upper(name) = upper(nm) and id is distinct from pid) then
    raise exception 'Un partenaire porte déjà ce nom.';
  end if;
  if pid is null then
    insert into accounts(name, kind, phone, note, allow_negative, sort) values (nm, 'fournisseur', _txt(p,'contacts'), _txt(p,'note'), true, 200)
      returning id into acc;
    insert into partenaires(account_id, name) values (acc, nm) returning * into r;
  else
    r := _part(pid);
  end if;
  update partenaires set name = nm, country = _txt(p,'country'), contacts = _txt(p,'contacts'), products = _txt(p,'products'),
    bank_details = _txt(p,'bank_details'), momo = _txt(p,'momo'), conditions = _txt(p,'conditions'),
    payment_terms = _txt(p,'payment_terms'), note = _txt(p,'note'),
    cartes_compensees = coalesce((p->>'cartes_compensees')::boolean, cartes_compensees),
    active = coalesce((p->>'active')::boolean, active)
  where id = r.id returning * into r;
  update accounts set name = nm, active = r.active where id = r.account_id;
  -- Dettes cartes suivies à part : un compte séparé.
  if not r.cartes_compensees and r.cards_account_id is null then
    insert into accounts(name, kind, allow_negative, sort, is_cards, note)
      values (nm || ' (cartes)', 'fournisseur', true, 201, true, 'Dettes liées aux achats de cartes') returning id into acc;
    update partenaires set cards_account_id = acc where id = r.id returning * into r;
  elsif r.cards_account_id is not null then
    update accounts set name = nm || ' (cartes)' where id = r.cards_account_id;
  end if;
  perform _log('accounts');
  return to_jsonb(r);
end $$;

create or replace function list_partenaires(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles;
begin
  me := _require(null);
  return (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', x.id, 'name', x.name, 'country', x.country, 'products', x.products, 'active', x.active,
      'account_id', x.account_id, 'cards_account_id', x.cards_account_id, 'cartes_compensees', x.cartes_compensees,
      'position', _bal(x.account_id),
      'cards_position', case when x.cards_account_id is not null then _bal(x.cards_account_id) end,
      'pending_n', (select count(*) from partner_ops d where d.partenaire_id = x.id and d.status in ('en_attente','en_cours','partiel')),
      'last_at', (select max(created_at) from partner_ops d where d.partenaire_id = x.id)
    ) order by x.active desc, x.name), '[]')
    from partenaires x
    where _can(me, 'fournisseurs') or x.active);
end $$;

-- Fiche complète : position, demandes en attente, commandes de cartes, historique.
create or replace function get_partenaire(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; pa partenaires; canp boolean;
begin
  me := _require(null);
  pa := _part(_num(p,'id')::bigint);
  canp := _can(me, 'fournisseurs');
  return to_jsonb(pa) || jsonb_build_object(
    'position', _bal(pa.account_id),
    'cards_position', case when pa.cards_account_id is not null then _bal(pa.cards_account_id) end,
    'can_manage', canp,
    'pending', (select coalesce(jsonb_agg(_pop_row(d, canp) order by d.created_at desc), '[]') from partner_ops d
                where d.partenaire_id = pa.id and d.status in ('en_attente','en_cours','partiel')
                  and (canp or d.type in ('recharge','paiement','transfert_in','transfert_out'))),
    'cartes', (select coalesce(jsonb_agg(_pop_row(d, canp) order by d.created_at desc), '[]') from partner_ops d
               where d.partenaire_id = pa.id and d.type = 'cartes' and d.status <> 'annulee'
                 and (d.status in ('en_attente','partiel') or d.created_at > now() - interval '90 days')),
    'recent', (select coalesce(jsonb_agg(_pop_row(d, canp) order by d.created_at desc), '[]') from (
                select * from partner_ops d where d.partenaire_id = pa.id
                  and (canp or d.type in ('recharge','paiement','transfert_in','transfert_out'))
                order by d.created_at desc limit 60) d)
  );
end $$;

-- Liste des dossiers (filtres : partenaire, type, statut, période, recherche).
create or replace function list_dossiers(p jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare me profiles; canp boolean; st text := _txt(p,'status'); q text := upper(coalesce(_txt(p,'q'), ''));
begin
  me := _require(null);
  canp := _can(me, 'fournisseurs');
  return (
    select coalesce(jsonb_agg(_pop_row(d, canp) order by d.created_at desc), '[]') from (
      select * from partner_ops d
      where (_num(p,'partenaire_id') is null or d.partenaire_id = _num(p,'partenaire_id')::bigint)
        and (_txt(p,'type') is null or d.type = _txt(p,'type'))
        and (st is null or (st = 'pending' and d.status in ('en_attente','en_cours','partiel')) or d.status = st)
        and (_txt(p,'from') is null or d.created_at::date >= _txt(p,'from')::date)
        and (_txt(p,'to') is null or d.created_at::date <= _txt(p,'to')::date)
        and (q = '' or upper(coalesce(d.ref,'') || ' ' || coalesce(d.beneficiary,'') || ' ' || coalesce(d.client_name,'') || ' '
             || coalesce(d.reference,'') || ' ' || coalesce(d.donneur,'') || ' ' || coalesce((select name from clients where id = d.client_id), '')) like '%' || q || '%')
        and (canp or (d.type in ('recharge','paiement','transfert_in','transfert_out')
                      and (me.role = 'gerante' or d.agence_id = me.agence_id)))
      order by d.created_at desc
      limit least(coalesce(_num(p,'limit')::int, 200), 1000)) d);
end $$;

